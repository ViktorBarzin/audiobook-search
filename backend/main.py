async def _notify_slack(title: str, author: str, content_type: str, source: str = "", kindle: bool = False):
    """Send download notification to Slack. Fire-and-forget, never fails the request."""
    if not SLACK_WEBHOOK_URL:
        return
    try:
        emoji = "\U0001f4d6" if content_type == "ebook" else "\U0001f3a7"
        kindle_tag = " \u2192 Kindle" if kindle else ""
        text = f"{emoji} *{title}*\nby {author}\n_{content_type}{kindle_tag}_"
        if source:
            text += f" | source: {source}"
        async with httpx.AsyncClient(timeout=5) as client:
            await client.post(SLACK_WEBHOOK_URL, json={"text": text})
    except Exception as e:
        logger.warning(f"Slack notification failed: {e}")


def _chown_for_cwa(path: str):
    """Set file ownership and permissions so CWA (abc user) can manage it."""
    try:
        os.chown(path, CWA_UID, CWA_GID)
        os.chmod(path, 0o664)
    except OSError as e:
        logger.warning(f"Failed to set ownership on {path}: {e}")


def _publish_ingest_file(file_data: bytes, filename: str) -> str:
    """Write a complete ebook into the ingest directory atomically.

    CWA watches the NFS directory and may open a recognized ebook extension as
    soon as it appears. Keep the download under a non-ebook `.part` name, then
    rename it after the write and permission changes are complete.
    """
    os.makedirs(CWA_INGEST_PATH, exist_ok=True)
    filename = os.path.basename(filename)
    save_path = os.path.join(CWA_INGEST_PATH, filename)
    temp_path = os.path.join(CWA_INGEST_PATH, f".{filename}.{uuid.uuid4().hex}.part")
    try:
        with open(temp_path, "wb") as f:
            f.write(file_data)
            f.flush()
            os.fsync(f.fileno())
        _chown_for_cwa(temp_path)
        os.replace(temp_path, save_path)
        return save_path
    finally:
        if os.path.exists(temp_path):
            os.unlink(temp_path)


def _prepare_audiobook_save_path(save_path: str) -> None:
    """Create qBittorrent's destination before a magnet enters the queue.

    The orphan sweeper treats a missing destination as abandoned. Magnet links
    can spend time fetching metadata before qBittorrent creates that directory,
    so creating it here closes the race and gives the media user write access.
    """
    os.makedirs(save_path, exist_ok=True)
    try:
        os.chown(save_path, CWA_UID, CWA_GID)
        os.chmod(save_path, 0o775)
    except OSError as e:
        logger.warning(f"Failed to set audiobook destination permissions on {save_path}: {e}")


async def _periodic_fix_ingest_permissions():
    """Fix permissions on files in CWA ingest dir (Stacks writes as root:1000 mode 644)."""
    while True:
        try:
            if os.path.isdir(CWA_INGEST_PATH):
                for entry in os.scandir(CWA_INGEST_PATH):
                    if entry.is_file():
                        st = entry.stat()
                        if st.st_uid != CWA_UID or st.st_gid != CWA_GID or st.st_mode & 0o777 != 0o664:
                            _chown_for_cwa(entry.path)
                            logger.info(f"Fixed permissions on {entry.name}")
        except Exception as e:
            logger.warning(f"Permission fixer error: {e}")
        await asyncio.sleep(5)


async def _periodic_fix_library_permissions():
    """Fix permissions on recently modified files in Calibre library.

    CWA's NETWORK_SHARE_MODE=true skips chown after import, leaving files
    as root:abc 644. We fix ownership to abc:abc so CWA can manage them.
    Only scans files modified in the last 10 minutes to avoid NFS thrash.
    """
    while True:
        try:
            if os.path.isdir(CWA_LIBRARY_PATH):
                now = time.time()
                cutoff = now - 600  # last 10 minutes
                for dirpath, dirnames, filenames in os.walk(CWA_LIBRARY_PATH):
                    try:
                        dst = os.stat(dirpath)
                        if dst.st_mtime < cutoff:
                            dirnames.clear()  # skip old subtrees
                            continue
                        if dst.st_uid != CWA_UID:
                            os.chown(dirpath, CWA_UID, CWA_GID)
                            os.chmod(dirpath, 0o755)
                        for fname in filenames:
                            fpath = os.path.join(dirpath, fname)
                            fst = os.stat(fpath)
                            if fst.st_uid != CWA_UID:
                                os.chown(fpath, CWA_UID, CWA_GID)
                                os.chmod(fpath, 0o644)
                                logger.info(f"Fixed library permissions on {fname}")
                    except OSError:
                        pass
        except Exception as e:
            logger.warning(f"Library permission fixer error: {e}")
        await asyncio.sleep(30)


