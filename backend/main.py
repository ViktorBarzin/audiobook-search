CALIBRE_ID_ATTEMPTS = 12
CALIBRE_ID_INTERVAL = 10
# How long an id lookup keeps waiting while Calibre still has an upload in the
# ingest folder. A PDF is converted to EPUB on import, which took minutes on
# 2026-09-24; CWA's own ingest timeout is 15 minutes.
CALIBRE_IMPORT_MAX_WAIT = int(os.getenv("CALIBRE_IMPORT_MAX_WAIT", "1200"))

# Anna's Archive builds every page title as "<page title> - <site title>"
# (allthethings/templates/layouts/index.html), so a title shared from the iOS
# share sheet arrives as "Obviously Awesome - Anna's Archive". The magnifier
# glyph appears in some of their headings. Stripping this here costs one regex
# and saves building text-manipulation actions inside Shortcuts.
_AA_TITLE_SUFFIX_RE = _re.compile(
    r"\s*[-–—|]?\s*(?:\U0001F50D\s*)?[-–—|]?\s*Anna[’']?s?\s+Archive\s*$",
    _re.IGNORECASE,
)
_TRAILING_GLYPH_RE = _re.compile(r"\s*\U0001F50D\s*$")


def _clean_shared_title(shared: str | None) -> str:
    """Turn a shared page title into something searchable.

    Returns "" when nothing but the site name was shared, which happens if the
    share came from Anna's Archive's homepage rather than a book page.
    """
    if not shared:
        return ""
    cleaned = _AA_TITLE_SUFFIX_RE.sub("", shared.strip())
    cleaned = _TRAILING_GLYPH_RE.sub("", cleaned)
    return cleaned.strip()


def _searchable_title(title: str | None) -> bool:
    """A title worth looking up. "Unknown" is what a bare md5 share carries."""
    if not title or is_placeholder(title):
        return False
    return normalize_title(title) not in ("", "unknown")


def _real_author(author: str | None) -> str:
    """The author, or "" for the placeholder a share with no author carries."""
    return "" if normalize_author(author) in ("", "unknown", "unknown author") else (author or "")


def _name_pairs(title: str, author: str, also=()) -> list[tuple[str, str]]:
    """The (title, author) pairs worth looking a book up by.

    A pair that names an author outranks one that does not: a share with only
    the title "Principles" must not settle on Carnap's book when the EPUB
    itself names Ray Dalio.
    """
    pairs = [(t, a or "") for t, a in [(title, author), *also] if _searchable_title(t)]
    with_author = [(t, a) for t, a in pairs if _real_author(a)]
    return with_author or pairs


def _ebook_meta(data: bytes, filename: str) -> tuple[str, str] | None:
    """The title and author an EPUB names for itself, or None.

    Calibre files an EPUB under its own OPF title, which can differ from the
    Anna's Archive page title the job carries ("The Hobbit" against "The
    Hobbit, or There and Back Again"). Knowing both lets the library lookup
    find the book either way.
    """
    if not data or not data.startswith(b"PK"):
        return None
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as epub:
            def small(name):
                if epub.getinfo(name).file_size > 1_000_000:
                    raise ValueError(f"{name} is too large to be metadata")
                return epub.read(name)

            container = ET.fromstring(small("META-INF/container.xml"))
            opf_path = next((el.get("full-path") for el in container.iter()
                             if el.tag.endswith("rootfile") and el.get("full-path")), None)
            if not opf_path:
                return None
            opf = ET.fromstring(small(opf_path))
    except Exception:
        return None
    title = next((el.text.strip() for el in opf.iter()
                  if el.tag.endswith("}title") and el.text and el.text.strip()), None)
    if not title:
        return None
    author = next((el.text.strip() for el in opf.iter()
                   if el.tag.endswith("}creator") and el.text and el.text.strip()), "")
    return title, author


async def _confirm_calibre_id(job: dict, title: str, author: str, hint: int | None) -> int | None:
    """The library's id for a book just uploaded. The OPDS id is only a hint.

    _upload_to_calibre searches OPDS with terms taken from the file name, and
    for a libgen file the first term is the author ("Sophie Kinsella"), so it
    can answer with another book by the same author. A hint is kept only when
    the library row it names is the book this job fetched, or when there is
    nothing to check it against: no library mounted, or no usable title.
    """
    also = [tuple(job["file_meta"])] if job.get("file_meta") else []
    newer_than = job.get("library_max_id")
    if not hint or hint <= 0:
        return await _resolve_calibre_id(title, author, also=also, newer_than=newer_than)
    if not os.path.exists(os.path.join(CWA_LIBRARY_PATH, "metadata.db")):
        return hint
    added_since = newer_than is not None and hint > newer_than
    names = _name_pairs(title, author, also)
    if not names:
        # Nothing names the book. Only a row the upload added can be it.
        return hint if added_since else None
    row = _calibre_book(hint)

    def vouches(t: str, a: str) -> bool:
        if not row or not _same_book(row[0], row[1], t, a):
            return False
        return bool(_real_author(a)) or added_since

    if any(vouches(t, a) for t, a in names):
        return hint
    logger.warning(
        "OPDS named book %s (%r) for %r; finding the right one in the library",
        hint, row[0] if row else None, title,
    )
    return await _resolve_calibre_id(title, author, also=also, newer_than=newer_than)


async def _resolve_calibre_id(title: str, author: str, also=(), newer_than: int | None = None) -> int | None:
    """Ask the library database for a freshly imported book's id.

    _upload_to_calibre gets the id from an OPDS poll that stops at the first
    non-None answer, and _opds_search answers -1 when it finds an entry with no
    downloadable format yet — which is what CWA looks like mid-import. So a book
    that imports a moment later resolves to -1, and every consumer of that id
    quietly does nothing: on 2026-09-04 Obviously Awesome was in the library as
    id 507 ten seconds after the upload call had given up.

    The Goodreads path already reads metadata.db, matched on title AND author.
    This is the same wait, for the shortcut path.

    While Calibre still has an upload in the ingest folder it is still
    importing, so those looks do not count against CALIBRE_ID_ATTEMPTS; only
    CALIBRE_IMPORT_MAX_WAIT bounds them. On 2026-09-24 a PDF was still being
    converted when the fixed 12 looks ran out, and the Kindle send was skipped.

    `also` holds more (title, author) pairs to try, such as the ones the EPUB
    names for itself, which is what Calibre files it under. A pair with no
    author only matches a row numbered above `newer_than`, the library's
    highest id before the upload, and never when that is unknown: a title
    alone cannot tell two books apart, but "added just now" can.
    """
    names = _name_pairs(title, author, also)
    names = [(t, a) for t, a in names if _real_author(a) or newer_than is not None]
    if not names:
        return None
    deadline = time.monotonic() + CALIBRE_IMPORT_MAX_WAIT
    idle_looks = 0
    while True:
        for name_title, name_author in names:
            if _real_author(name_author):
                book_id = _calibre_id_for(name_title, name_author)
            else:
                book_id = _calibre_id_for(name_title, name_author, newer_than=newer_than)
            if book_id:
                return book_id
        if _cwa_uploads_pending():
            idle_looks = 0
        else:
            idle_looks += 1
            if idle_looks >= CALIBRE_ID_ATTEMPTS:
                return None
        if time.monotonic() >= deadline:
            return None
        await asyncio.sleep(CALIBRE_ID_INTERVAL)


def _no_route_message(md5: str, title: str, upstream: str | None = None) -> str:
    """Say which routes were tried and what would open one.

    The old text was whatever Stacks last said — "No mirrors found" — which
    reads like the book does not exist. On 2026-09-04 it meant libgen had no
    file for that md5 and Anna's Archive was 403, while the book was on libgen
    under other hashes. Naming the missing input is what makes the difference
    actionable from a phone.
    """
    if not title or is_placeholder(title) or title == "Unknown":
        return (
            f"No download route for {md5}: libgen has no file for this hash and "
            "Anna's Archive is unreachable, so the title is unknown and cannot "
            "be searched for. Re-share with the book's title to search libgen "
            "by name."
        )
    detail = f" (upstream: {upstream})" if upstream else ""
    return (
        f"No download route for {title!r}: libgen has no file for md5 {md5} and "
        f"no confident title match, and Anna's Archive is unreachable{detail}."
    )


_AUTHOR_QUALIFIER_RE = _re.compile(r"\s*[,;]?\s*\([^)]*\)\s*$")


def _clean_shared_author(author: str | None) -> str:
    """Drop the occupation qualifier Anna's Archive appends to an author.

    Its metadata carries them: "Rob Fitzpatrick, (Entrepreneur)", and the
    library already holds "Valerie Howard (Writer on Juvenile literature)" from
    the same source. The surname matcher reads the last token, so a qualifier
    becomes the surname and no candidate can ever match.
    """
    cleaned = _AUTHOR_QUALIFIER_RE.sub("", (author or "").strip()).strip(" ,;")
    return cleaned or (author or "").strip()


def _libgen_queries(title: str, author: str) -> list[str]:
    """Progressively shorter libgen queries, first one first.

    A whole subtitle in the query returns nothing: The Mom Test found 0 rows on
    2026-09-07 for its full 110-character title, and 5 rows for "The Mom Test
    Rob Fitzpatrick" on the same mirror seconds later. Only the search net
    widens here. Identity is still settled against the full title and the real
    author, so a shorter query means more rows to reject, never a weaker test.
    """
    forms: list[str] = []

    def add(query: str) -> None:
        query = " ".join(query.split())
        if query and query not in forms:
            forms.append(query)

    add(f"{title} {author}")
    main = title.split(":")[0].strip()
    add(f"{main} {author}")
    add(main)
    return forms


# A mirror having a bad day should not turn one book into 25 requests.
FALLBACK_FILE_ATTEMPTS = int(os.getenv("FALLBACK_FILE_ATTEMPTS", "4"))
# Files of one book offered to Calibre before a share gives up on refusals.
FALLBACK_UPLOAD_ATTEMPTS = int(os.getenv("FALLBACK_UPLOAD_ATTEMPTS", "3"))


async def _libgen_find_file(
    title: str, author: str, skip=frozenset(), want=None,
) -> tuple[bytes | None, str | None, str | None]:
    """Find the same book on libgen under a different hash: (data, filename, md5).

    An md5 shared from Anna's Archive names one FILE. libgen mirrors most books
    many times over, but not always that exact file: Obviously Awesome (April
    Dunford) arrived on 2026-09-04 as an AA-only md5 that libgen's ads.php and
    md5 search both had nothing for, while the book itself sat there under a
    dozen other hashes.

    Identity is settled by title AND author through the shared matcher, which is
    what keeps this from repeating the fuzzy last-word search that once shelved
    a CISSP study guide as Neuromancer. No confident match means no download.

    `skip` holds the hashes already tried or refused. Excluding them matters: on
    2026-09-07 The Mom Test matched its own AA hash here and went back to the
    CDN that had just answered 503 three times, while libgen had the book under
    four other hashes. A file that fails to download is dropped and the matcher
    runs again on what is left, up to FALLBACK_FILE_ATTEMPTS files, so a mirror
    with one bad file does not end the job.

    `want` narrows the rows the matcher may choose from, such as "not a PDF,
    small enough to email" when a Kindle share looks for an EPUB.
    """
    title = _clean_shared_title(title)
    if not libgen_scraper or not title or is_placeholder(title):
        return None, None, None
    if normalize_title(title) == normalize_title("Unknown"):
        return None, None, None

    author = _clean_shared_author(author)
    item = ShelfItem(book_id="", title=title, author=author, isbn=None, added_at=None)
    skip = {m.lower() for m in skip if m}

    def choose(rows: list):
        if author:
            match = select_candidate(item, rows)
            return match.candidate, match.reason
        return _pick_on_title_alone(title, rows), "title_only"

    candidates: list = []
    for query in _libgen_queries(title, author):
        try:
            rows = await libgen_scraper.search_candidates(query)
        except Exception as e:
            logger.warning(f"LibGen title search failed for {query!r}: {type(e).__name__}: {e}")
            return None, None, None
        # Dropping the tried hashes BEFORE deciding the query answered. The
        # full-title query for The Mom Test returned exactly one row, that very
        # hash, on 2026-09-07, so the loop stopped and the filter then emptied
        # it. The shorter query that finds the book five times over on the same
        # mirror was never sent.
        rows = [c for c in rows
                if (c.md5 or "").lower() not in skip and (want is None or want(c))]
        # A query has answered only when the matcher accepts one of its rows.
        # On 2026-09-24 the full title of A Man Called Ove returned a single
        # companion book by another author; stopping there failed the job while
        # the shorter query found the novel.
        if rows and choose(rows)[0]:
            candidates = rows
            break
        logger.info(
            "No acceptable libgen rows for %r (%d rows), trying a shorter query", query, len(rows),
        )

    remaining = list(candidates)
    for attempt in range(FALLBACK_FILE_ATTEMPTS):
        chosen, how = choose(remaining)

        if not chosen:
            logger.info(
                "No confident libgen match for %r by %r (%d candidates)",
                title, author or "(no author)", len(remaining),
            )
            return None, None, None

        logger.info(
            "Falling back to libgen md5 %s for %r by %r (matched on %s, try %d)",
            chosen.md5, title, author or "(no author)", how, attempt + 1,
        )
        try:
            data, filename = await libgen_scraper.download_file(chosen.md5)
        except Exception as e:
            logger.warning(f"LibGen fallback download failed for {chosen.md5}: {e}")
            data, filename = None, None
        if data:
            return data, filename, chosen.md5
        # That file is not being served. The book is still the right one, so
        # take it out of the running and let the matcher pick again.
        remaining = [c for c in remaining if c.md5 != chosen.md5]

    logger.info(
        "Gave up on %r by %r after %d files", title, author or "(no author)",
        FALLBACK_FILE_ATTEMPTS,
    )
    return None, None, None


async def _libgen_by_title(
    title: str, author: str, skip_md5: str | None = None,
) -> tuple[bytes | None, str | None]:
    """_libgen_find_file for a caller that needs only the file."""
    data, filename, _ = await _libgen_find_file(title, author, skip={skip_md5} if skip_md5 else set())
    return data, filename


async def _libgen_row_for(title: str, author: str, md5: str):
    """libgen's own row for one file, found by searching for its book, or None."""
    for query in _libgen_queries(_clean_shared_title(title), _clean_shared_author(author)):
        try:
            rows = await libgen_scraper.search_candidates(query)
        except Exception:
            return None
        for row in rows:
            if (row.md5 or "").lower() == md5.lower():
                return row
    return None


async def _reflowable_instead(
    title: str, author: str, pdf_md5: str,
) -> tuple[bytes | None, str | None, str | None]:
    """An EPUB (or AZW3/MOBI) of the same book for a Kindle, or nothing.

    A PDF keeps its page layout on a six-inch screen, so it arrives as pages to
    pinch and pan; two of the three shares on 2026-09-24 were PDFs. The swap
    needs the shared file's language: only an English original is swapped,
    since the matcher offers English files only, and a PDF whose language
    libgen does not state is kept rather than risk another translation.
    """
    if not libgen_scraper or not _searchable_title(title):
        return None, None, None
    original = await _libgen_row_for(title, author, pdf_md5)
    if not original or not is_english(original.language):
        logger.info("Keeping the PDF of %r: its language is %r", title,
                    original.language if original else "not listed")
        return None, None, None

    def reflowable(row) -> bool:
        return (row.ext or "").lower() != "pdf" and (row.size_bytes or 0) <= MAX_BOOK_BYTES

    return await _libgen_find_file(title, author, skip={pdf_md5}, want=reflowable)


def _pick_on_title_alone(title: str, candidates: list) -> object | None:
    """Choose a file from a title with no author to corroborate it.

    Anna's Archive page titles carry no author, so a book shared from a phone
    arrives as a title and nothing else. Two rules keep that from picking the
    wrong book, which is a real failure here: a fuzzy search once shelved a
    CISSP study guide as Neuromancer because both list a Gibson.

    1. The title must agree under _titles_agree, which allows the offered title
       to extend the wanted one with bookkeeping tokens but not with a real
       word. So "Dune" cannot take "Dune Messiah". Plain equality is too strict
       to be usable: searching "Thinking, Fast and Slow" on 2026-09-04 returned
       25 candidates and not one had a clean title, because libgen's title cell
       absorbs edition wording and ISBNs ("Thinking, Fast and Slow 1st ed
       9780141033570", "Thinking Fast And Slow b l 4322674").
    2. Every title-matching candidate must agree on one author surname. Where
       two real books share a title ("Principles" by Dalio and by Carnap) there
       is nothing to choose between them, so nothing is chosen.
    """
    matching = [c for c in candidates if _is_usable(c) and _titles_agree(title, c.title)]
    if not matching:
        return None

    surnames = {author_surname(c.author) for c in matching}
    surnames.discard("")
    if len(surnames) != 1:
        logger.info(
            "Title %r is ambiguous without an author: %d candidates across "
            "authors %s. Refusing to guess.",
            title, len(matching), sorted(surnames) or ["(none)"],
        )
        return None

    return sorted(matching, key=_rank)[0]


async def _try_direct_download(job_id: str, job: dict, md5: str, title: str, author: str, detail, mirror_urls: list[str] = None) -> bool:
    """Attempt direct download from libgen mirrors or provided mirror URLs.
    Returns True if uploaded to Calibre."""
    # An md5 on its own is enough: libgen's keyed ads.php -> get.php serves files
    # by hash, including ones its own search does not index. This matters because
    # Anna's Archive detail pages are unreachable from here, so a book shared
    # from AA arrives as a bare md5 — which used to end the job right here with
    # "All download methods failed" while that same md5 downloaded fine.
    # The hash route runs FIRST whatever else we were handed. It used to be
    # gated on having no detail, which was fine while Anna's Archive detail
    # pages were unreachable and a detail therefore never existed. Now the
    # phone can post the rendered page, so a detail is common — and its mirrors
    # are /slow_download/ links we cannot use. Leading with them would step
    # around the one route that actually delivers.
    if not mirror_urls:
        if not libgen_scraper:
            return False
        try:
            file_data, filename = await libgen_scraper.download_file(md5)
        except Exception as e:
            logger.warning(f"LibGen md5 download failed for {md5}: {e}")
            file_data, filename = None, None
        used_md5 = md5
        if not file_data:
            # libgen has no file for this exact hash. The book may still be
            # there under another one, if the caller told us what it is.
            job["stage_detail"] = "Not on libgen by hash, searching by title..."
            file_data, filename, used_md5 = await _libgen_find_file(title, author, skip={md5})
        if not file_data or len(file_data) < MIN_EBOOK_SIZE_BYTES:
            # Fall through to the detail's own mirrors rather than giving up.
            file_data = None

        if file_data:
            filename = filename or f"{author} - {title}.epub"
            logger.info(f"Fetched {used_md5} from libgen: {filename}")
            return await _upload_best_file(job, md5, used_md5, file_data, filename, title, author)

    if not detail:
        return False

    # Build list of URLs to try
    urls_to_try = []

    # Add explicitly provided mirror URLs first
    if mirror_urls:
        urls_to_try.extend(mirror_urls)

    # Add detail.mirror_urls if available
    if hasattr(detail, "mirror_urls") and detail.mirror_urls:
        urls_to_try.extend([u for u in detail.mirror_urls if u not in urls_to_try])

    # Add magnet_url as fallback
    if detail.magnet_url and detail.magnet_url not in urls_to_try:
        urls_to_try.append(detail.magnet_url)

    # Filter to only direct-download-capable mirrors (or try all if none are direct)
    direct_urls = [u for u in urls_to_try if any(h in u for h in ("libgen", "library.lol", "gen.lib"))]
    if direct_urls:
        urls_to_try = direct_urls

    if not urls_to_try:
        return False

    # Try each URL in sequence
    for idx, dl_url in enumerate(urls_to_try):
        try:
            job["stage_detail"] = f"Recovering via direct download ({idx+1}/{len(urls_to_try)})..."
            logger.info(f"[{job_id}] Trying direct download from {dl_url}")
            file_data, filename = await annas_scraper.download_file(dl_url)
            if not file_data:
                logger.warning(f"[{job_id}] Direct download failed from {dl_url}")
                continue
            if not filename:
                ext = ".pdf" if file_data[:4] == b"%PDF" else ".epub"
                filename = f"{author} - {title}{ext}"
            job["status"] = "downloaded"
            job["filename"] = filename
            logger.info(f"[{job_id}] Direct download got {filename} from {dl_url}, uploading to CWA")
            # Every mirror serves the same md5, so a file Calibre refuses from
            # one would be refused from the next as well.
            return await _upload_and_confirm(job, file_data, filename, title, author)
        except Exception as e:
            logger.warning(f"[{job_id}] Direct download attempt {idx+1}/{len(urls_to_try)} failed for {dl_url}: {e}")
            continue

    # All mirrors failed — try LibGen MD5 lookup as last resort
    try:
        job["stage_detail"] = "Trying LibGen MD5 lookup..."
        logger.info(f"[{job_id}] Trying LibGen MD5 lookup for {md5}")
        file_data, filename = await annas_scraper.download_from_libgen_md5(md5)
        if file_data:
            if not filename:
                ext = ".pdf" if file_data[:4] == b"%PDF" else ".epub"
                filename = f"{author} - {title}{ext}"
            job["status"] = "downloaded"
            job["filename"] = filename
            logger.info(f"[{job_id}] LibGen MD5 lookup got {filename}, uploading to CWA")
            return await _upload_and_confirm(job, file_data, filename, title, author)
    except Exception as e:
        logger.warning(f"[{job_id}] LibGen MD5 lookup failed for {md5}: {e}")

    return False


def _is_pdf(data: bytes, filename: str = "") -> bool:
    # Calibre-Web sniffs with libmagic, but some libgen PDFs carry stray bytes
    # before %PDF (a Moby-Dick copy on 2026-09-24), so the name counts too.
    return data[:4] == b"%PDF" or filename.lower().endswith(".pdf")


async def _upload_best_file(job: dict, shared_md5: str, md5: str, file_data: bytes,
                            filename: str, title: str, author: str) -> bool:
    """Get one file of this book into Calibre, trying the known fixes first.

    For a Kindle share of a PDF, an EPUB of the same book goes first and the
    PDF stays as the fallback. When Calibre-Web refuses a file, the next file
    of the same book is tried, up to FALLBACK_UPLOAD_ATTEMPTS uploads; a
    refusal says something about that file, not about the book. When Calibre
    is unreachable, nothing more is tried.
    """
    tried = {shared_md5, md5}
    job["tried_md5s"] = tried
    queue = [(file_data, filename, md5)]
    swapped_md5 = None
    if job.get("kindle_email") and _is_pdf(file_data, filename):
        job["stage_detail"] = "Looking for an EPUB to send instead of the PDF..."
        epub, epub_name, epub_md5 = await _reflowable_instead(title, author, md5)
        if epub and len(epub) >= MIN_EBOOK_SIZE_BYTES:
            logger.info("Sending an EPUB of %r (%s) instead of the PDF %s", title, epub_md5, md5)
            queue.insert(0, (epub, epub_name or f"{author} - {title}.epub", epub_md5))
            tried.add(epub_md5)
            swapped_md5 = epub_md5

    for _ in range(FALLBACK_UPLOAD_ATTEMPTS):
        if not queue:
            job["stage_detail"] = "Calibre refused that file, trying another copy of the book..."
            more, more_name, more_md5 = await _libgen_find_file(title, author, skip=tried)
            if not more or len(more) < MIN_EBOOK_SIZE_BYTES:
                break
            tried.add(more_md5)
            queue.append((more, more_name or f"{author} - {title}.epub", more_md5))
        data, name, file_md5 = queue.pop(0)
        if await _upload_and_confirm(job, data, name, title, author):
            job.pop("upload_refused", None)
            if file_md5 == swapped_md5:
                job["swapped_from"] = "pdf"
            job["stage_detail"] = f"Downloaded {name} ({len(data)} bytes)"
            return True
        if job.get("calibre_down"):
            return False
        logger.info("Calibre refused %s (%s)", name, file_md5)
    return False


async def _upload_and_confirm(job: dict, file_data: bytes, filename: str, title: str, author: str) -> bool:
    """Upload a file to Calibre-Web and find the book in the library.

    Returns False when Calibre-Web turns the file away, with the reason in
    job["upload_refused"], or cannot take any file, with the reason in
    job["calibre_down"]. An accepted upload returns True whether or not the
    library shows the book yet; job["book_id"] is set only once it does.
    """
    job["phase"] = "uploading"
    job["stage_detail"] = "Uploading to Calibre..."
    job["format"] = "pdf" if file_data[:4] == b"%PDF" else (os.path.splitext(filename)[1].lstrip(".").lower() or "epub")
    job["file_meta"] = _ebook_meta(file_data, filename)
    job["library_max_id"] = _calibre_max_id()
    try:
        hint = await _upload_to_calibre(file_data, filename)
    except CalibreUnreachable as e:
        job["calibre_down"] = (f"Calibre-Web is unreachable ({e}), so nothing could be "
                               "added. Share it again once Calibre is back")
        return False
    if not hint:
        job["upload_refused"] = (
            f"Calibre-Web did not accept {filename}. It turns away files it "
            "cannot identify as a book, so try a different copy, ideally an "
            "EPUB; if that fails too, Calibre itself may be down."
        )
        return False
    # Calibre converts a PDF on import, which took minutes on 2026-09-24. A
    # phone that is still waiting is told to stop and read Slack instead.
    job["phase"] = "converting" if job["format"] == "pdf" else "importing"
    job["stage_detail"] = "Uploaded, waiting for Calibre to import..."
    book_id = await _confirm_calibre_id(job, title, author, hint)
    job["book_id"] = book_id
    job["book_id_confirmed"] = bool(book_id)
    if not book_id:
        job["code"] = "calibre_id"
        job["reason"] = "Calibre took the file, but the book never showed up in the library"
    elif not _searchable_title(job.get("title")):
        # A bare md5 share arrives as "Unknown"; the library knows better.
        row = _calibre_book(book_id)
        if row and row[0]:
            job["title"], job["author"] = row[0], row[1] or job.get("author")
    return True


async def _cwa_login(client: httpx.AsyncClient) -> bool:
    """Log into CWA and establish session. Returns True on success."""
    import re
    r = await client.get(f"{CALIBRE_WEB_URL}/login")
    if r.status_code != 200:
        return False
    m = re.search(r'name="csrf_token"\s+value="([^"]+)"', r.text)
    if not m:
        return False
    login_data = {
        "username": CALIBRE_WEB_USER,
        "password": CALIBRE_WEB_PASS,
        "csrf_token": m.group(1),
        "submit": "",
    }
    r = await client.post(f"{CALIBRE_WEB_URL}/login", data=login_data)
    return r.status_code == 200


def _smtp_send_with_retry(msg, max_attempts: int = SMTP_MAX_ATTEMPTS) -> None:
    """Send `msg` via SMTP with exponential-backoff retry on transient errors.

    Retries on the errors in `_SMTP_RETRIABLE_EXC` (server disconnects, banner
    timeouts, ConnectionError). Non-retriable errors (auth failure, malformed
    message) propagate after the first failure. Raises the last retriable
    exception if all attempts fail.
    """
    last_exc: Exception | None = None
    for attempt in range(1, max_attempts + 1):
        try:
            with smtplib.SMTP(SMTP_HOST, SMTP_PORT, timeout=SMTP_TIMEOUT) as server:
                server.starttls()
                server.login(SMTP_USER, SMTP_PASS)
                server.send_message(msg)
            return
        except _SMTP_RETRIABLE_EXC as e:
            last_exc = e
            logger.warning(
                f"SMTP attempt {attempt}/{max_attempts} failed: "
                f"{type(e).__name__}: {e}"
            )
            if attempt < max_attempts:
                time.sleep(SMTP_RETRY_BACKOFF * (2 ** (attempt - 1)))
    assert last_exc is not None
    raise last_exc


class AlreadySent(str):
    """What _send_to_kindle returns when the send guard holds a repeat back.

    A str, so a caller that only knows "None means sent" still sees a reason;
    but not an error: nothing failed, the book already went. The callers that
    matter check for it and report a skip, never a failure, and never start a
    rescue over it.
    """

    at = ""


# Guard key -> {"at": epoch, "title", "book_id"}, mirrored in STATE_DIR/sends.json.
# Every send is stored under two keys (see _guard_keys).
_kindle_sends: dict[str, dict] = {}
# Guard keys with an email in flight right now.
_kindle_sending: set[str] = set()


def _sends_file() -> str:
    return os.path.join(STATE_DIR, "sends.json")


def _load_kindle_sends() -> None:
    """Merge the guard file into memory, keeping the newer entry per book.

    Read before every check: during a rolling update two pods run, and the
    other one may have sent since this one last looked.
    """
    try:
        with open(_sends_file()) as f:
            saved = json.load(f)
    except (OSError, ValueError):
        return
    if not isinstance(saved, dict):
        return
    for key, entry in saved.items():
        if not isinstance(entry, dict) or not isinstance(entry.get("at"), (int, float)):
            continue
        if entry["at"] > _kindle_sends.get(key, {}).get("at", 0):
            _kindle_sends[key] = entry


def _guard_text(text: str | None) -> str:
    """Blind to case and punctuation, but keeping every letter in any script,
    and the subtitle. normalize_title drops both, which made two different
    Bulgarian books, or two Sapiens subtitles, one book to the guard."""
    folded = unicodedata.normalize("NFKC", text or "").casefold()
    return " ".join(_re.findall(r"\w+", folded))


def _guard_keys(book_id: int, title: str, kindle_email: str) -> list[str]:
    """The keys a send is held and stored under.

    One names the library row, which holds even when the row cannot be read.
    The other names the book, so a rescued EPUB and the original PDF of one
    novel are one book: title and author from the library row when there is
    one, so every path names the book the same way whatever it was handed.
    """
    address = kindle_email.strip().lower()
    keys = [f"id:{book_id}|{address}"] if book_id and book_id > 0 else []
    row = _calibre_book(book_id)
    book_title, book_author = row if row and row[0] else (title, "")
    name = _guard_text(book_title)
    if name:
        surname = (_guard_text(book_author).split() or [""])[-1]
        keys.append(f"book:{name}|{surname}|{address}")
    return keys


def _held_by_guard(keys: list[str], kindle_email: str) -> "AlreadySent | None":
    where = _destination({"kindle_email": kindle_email})
    _load_kindle_sends()
    recent = [_kindle_sends[k]["at"] for k in keys
              if k in _kindle_sends and time.time() - _kindle_sends[k]["at"] < KINDLE_SEND_GUARD_SECONDS]
    if recent:
        held = AlreadySent(f"already sent to {where} at {_clock(max(recent))}")
        held.at = _clock(max(recent))
        return held
    return None


def _remember_send(keys: list[str], book_id: int, title: str) -> None:
    _load_kindle_sends()
    now = time.time()
    for key in keys:
        _kindle_sends[key] = {"at": now, "title": title, "book_id": book_id}
    for old in [k for k, v in _kindle_sends.items() if now - v["at"] >= KINDLE_SEND_GUARD_SECONDS]:
        del _kindle_sends[old]
    try:
        _write_json_atomic(_sends_file(), _kindle_sends)
    except OSError as e:
        logger.warning(f"Could not save the Kindle send guard: {e}")


async def _send_to_kindle(book_id: int, title: str, kindle_email: str,
                          formats: tuple[str, ...] = ("epub", "pdf")) -> str | None:
    """Email a book to a Kindle, once.

    Returns None when sent, an error string when the send failed, and an
    AlreadySent when this book reached this address in the last 24 hours. All
    three Kindle paths come through here (the shortcut's finally block,
    /api/send-to-kindle and the Goodreads ingest), so the guard covers them all.
    """
    keys = _guard_keys(book_id, title, kindle_email)
    # Another send of this book is in flight: wait for it, then decide. Its
    # failure must leave this one free to go.
    while any(key in _kindle_sending for key in keys):
        await asyncio.sleep(1)
    held = _held_by_guard(keys, kindle_email)
    if held:
        logger.info(f"Not sending {title!r} to {kindle_email}: {held}")
        return held
    _kindle_sending.update(keys)
    try:
        error = await _email_book(book_id, title, kindle_email, formats)
        if error is None:
            _remember_send(keys, book_id, title)
        return error
    finally:
        _kindle_sending.difference_update(keys)


async def _email_book(book_id: int, title: str, kindle_email: str,
                      formats: tuple[str, ...]) -> str | None:
    """Send book to Kindle email. Returns None on success, error string on failure.

    SMTP send retries up to SMTP_MAX_ATTEMPTS times with exponential backoff —
    mail.viktorbarzin.me has been observed to drop the connection before banner
    on intermittent days, so a single 500 should not surface to the user.
    """
    if not SMTP_USER or not SMTP_PASS:
        return "SMTP credentials not configured"
    try:
        auth = (CALIBRE_WEB_USER, CALIBRE_WEB_PASS) if CALIBRE_WEB_PASS else None
        async with httpx.AsyncClient(timeout=30, follow_redirects=True) as client:
            book_data = None
            fmt = None
            for try_fmt in formats:
                r = await client.get(f"{CALIBRE_WEB_URL}/opds/download/{book_id}/{try_fmt}/", auth=auth)
                if r.status_code == 200 and len(r.content) > 100:
                    book_data = r.content
                    fmt = try_fmt
                    break
            if not book_data:
                return f"No downloadable format found for book {book_id}"

        # Our relay caps a message at 20 MiB and answers an oversized one with a
        # bounce, long after the caller has been told the send succeeded. Catching
        # it here turns that into an error the caller can actually report.
        if len(book_data) > MAX_BOOK_BYTES:
            return (
                f"{fmt} for book {book_id} is too large to mail: "
                f"{len(book_data) / 1048576:.1f} MB, limit "
                f"{MAX_BOOK_BYTES / 1048576:.0f} MB"
            )

        from email.mime.multipart import MIMEMultipart
        from email.mime.application import MIMEApplication

        msg = MIMEMultipart()
        msg['From'] = SMTP_FROM
        msg['To'] = kindle_email
        msg['Subject'] = title
        safe_title = _re.sub(r'[^\w\s-]', '', title).strip()[:100] or "book"
        attachment = MIMEApplication(book_data, Name=f"{safe_title}.{fmt}")
        attachment['Content-Disposition'] = f'attachment; filename="{safe_title}.{fmt}"'
        msg.attach(attachment)

        await asyncio.get_event_loop().run_in_executor(None, _smtp_send_with_retry, msg)

        logger.info(f"Sent '{title}' to Kindle ({kindle_email})")
        return None
    except Exception as e:
        logger.exception(f"Failed to send '{title}' to Kindle ({kindle_email})")
        return str(e)


async def _process_download(job_id: str, md5: str, title: str, author: str, detail):
    """Background task that downloads a book and tracks progress through stages."""
    job = _download_jobs[job_id]
    # Initialize before the try so the finally clause can always reference it.
    pre_existing: set[str] = set()
    try:
        book_id = None
        # Sweep orphans (.MISMATCH leftovers, sub-5KB stubs from AA rate-limit
        # error pages) before queueing — otherwise the wait below could pick
        # one up and we'd email garbage to a Kindle. See _invalid_ingest_reason.
        swept = _sweep_ingest_orphans()
        if swept:
            logger.warning(f"[{job_id}] Swept {len(swept)} orphan ingest file(s) before queueing: {swept}")
        # Snapshot pre-existing valid files. Anything matching this set when the
        # wait functions poll is a leftover from another in-flight job, not
        # this download's payload — exclude it.
        try:
            pre_existing = set(os.listdir(CWA_INGEST_PATH))
        except OSError:
            pass
        job["pre_existing"] = pre_existing
        # Stage: downloading. Try the keyed libgen fetch FIRST — it is the route
        # that actually works. Stacks pulls from Anna's Archive, which is blocked
        # here, and it ACCEPTS an md5 before failing to deliver, so leading with
        # it left jobs waiting on a path that could never finish while libgen had
        # the file all along.
        job["status"] = "downloading"
        job["phase"] = "fetching"
        job["stage_detail"] = "Fetching from libgen..."
        if await _try_direct_download(job_id, job, md5, title, author, detail):
            job["status"] = "done"
            job["message"] = ("Added to Calibre" if job.get("book_id")
                              else "Uploaded to Calibre, but it has not shown up in the library")
            # No send here. The finally block below does it, and a return
            # inside a try runs finally anyway, which is how one tap put two
            # copies of the same book on a Kindle on 2026-09-07.
            return
        if job.get("calibre_down"):
            # No other file or route can help while Calibre cannot take one.
            job["status"] = "failed"
            job["code"] = "calibre_down"
            job["message"] = job["stage_detail"] = job["calibre_down"]
            return
        if job.get("upload_refused"):
            # The files downloaded fine and Calibre turned them down. Stacks
            # would only fetch the same file again, minutes later.
            job["status"] = "failed"
            job["code"] = "refused"
            job["message"] = job["stage_detail"] = job["upload_refused"]
            return

        job["stage_detail"] = "Sending to Stacks..."
        stacks_result = await annas_scraper.download_via_stacks(md5)
        stacks_ok = stacks_result.get("success")

        if not stacks_ok:
            # Fallback: direct download for libgen mirrors
            if not await _try_direct_download(job_id, job, md5, title, author, detail):
                job["status"] = "failed"
                if job.get("calibre_down"):
                    job["code"] = "calibre_down"
                    job["message"] = job["calibre_down"]
                elif job.get("upload_refused"):
                    job["code"] = "refused"
                    job["message"] = job["upload_refused"]
                else:
                    job["code"] = "no_route"
                    job["message"] = _no_route_message(
                        md5, title, upstream=stacks_result.get("error"),
                    )
                job["stage_detail"] = job["message"]
                return
            # _try_direct_download already uploaded via HTTP and set book_id.
            # Settle the job here: a caller polling for "done" (the iOS Shortcut)
            # would otherwise watch it sit on "downloading" forever.
            job["status"] = "done"
            job["message"] = "Added to Calibre"
            # The finally block sends. See the note on the path above.
            return
        else:
            already_downloaded = "already downloaded" in stacks_result.get("message", "").lower()
            logger.info(f"[{job_id}] Stacks accepted {md5} (already_downloaded={already_downloaded})")

            if already_downloaded:
                # Check if file is stuck in ingest dir — pick it up and upload via HTTP.
                # Don't exclude pre_existing here: "already_downloaded" means this very
                # md5 was completed previously, so the stuck file *is* the snapshot.
                stuck_files = _ingest_ebook_files()
                if stuck_files:
                    logger.info(f"[{job_id}] File stuck in ingest dir, uploading via HTTP: {stuck_files}")
                    file_path = os.path.join(CWA_INGEST_PATH, stuck_files[0])
                    with open(file_path, "rb") as f:
                        file_data = f.read()
                    os.remove(file_path)
                    job["status"] = "importing"
                    job["stage_detail"] = "Uploading to Calibre..."
                    book_id = await _upload_to_calibre(file_data, stuck_files[0])
                    if book_id is not None:
                        job["book_id"] = book_id
                        job["status"] = "done"
                        job["message"] = "Added to Calibre"
                        job["stage_detail"] = "Added to Calibre"
                    else:
                        job["status"] = "done"
                        job["message"] = "Uploaded — Calibre import may still be processing"
                        job["stage_detail"] = job["message"]
                    return

                # No file in ingest — quick OPDS check (maybe already imported)
                job["status"] = "importing"
                job["stage_detail"] = "Checking Calibre..."
                book_id = await _wait_for_calibre(title, timeout=15)
                if book_id is not None:
                    job["book_id"] = book_id
                    job["status"] = "done"
                    job["message"] = "Added to Calibre"
                    job["stage_detail"] = "Added to Calibre"
                    return

                # Book is gone — CWA consumed it but failed to import.
                # Delete Stacks history and force re-download.
                logger.warning(f"[{job_id}] Stacks 'already downloaded' but book missing from Calibre and ingest dir — forcing re-download")
                job["stage_detail"] = "Re-downloading (previous import failed)..."
                redownload_result = await annas_scraper.stacks_force_redownload(md5)
                if not redownload_result.get("success"):
                    # Stacks re-download failed — try direct download as last resort
                    recovered = await _try_direct_download(job_id, job, md5, title, author, detail)
                    if not recovered:
                        job["status"] = "done"
                        job["message"] = "Previously downloaded — not found in Calibre, re-download failed"
                        job["stage_detail"] = job["message"]
                        return
                    # _try_direct_download already uploaded via HTTP
                else:
                    pass  # Stacks re-download queued — fall through to wait for file

            # Wait for file to appear in ingest dir (fresh Stacks download or re-download)
            if job["status"] not in ("downloaded",):
                job["status"] = "downloading"
                job["stage_detail"] = "Waiting for download..."
                appeared, stacks_failed = await _wait_for_file_in_ingest_or_stacks_fail(
                    md5, timeout=180, exclude=pre_existing,
                )
                if appeared:
                    job["filename"] = appeared
                    logger.info(f"[{job_id}] File appeared in ingest: {appeared}")
                elif stacks_failed:
                    # Stacks reported failure — try direct download
                    logger.warning(f"[{job_id}] Stacks download failed, attempting direct download")
                    if await _try_direct_download(job_id, job, md5, title, author, detail):
                        # _try_direct_download already uploaded via HTTP and set book_id
                        pass
                    else:
                        job["status"] = "failed"
                        job["code"] = "no_route"
                        job["message"] = "All download methods failed"
                        job["stage_detail"] = job["message"]
                    return
                else:
                    # Timeout — but file may have arrived late. Check ingest dir one more time.
                    late_files = _ingest_ebook_files(exclude=pre_existing)
                    if late_files:
                        logger.info(f"[{job_id}] File arrived late in ingest dir: {late_files[0]}")
                        job["filename"] = late_files[0]
                        # Fall through to the "file is in ingest dir" block below
                    else:
                        # File truly not there — check OPDS, then try direct download
                        logger.warning(f"[{job_id}] File didn't appear in ingest dir after Stacks OK")
                        job["status"] = "importing"
                        job["stage_detail"] = "Download may be delayed, checking Calibre..."
                        book_id = await _wait_for_calibre(title, timeout=60)
                        if book_id is not None:
                            job["book_id"] = book_id
                            job["status"] = "done"
                            job["message"] = "Added to Calibre"
                            job["stage_detail"] = "Added to Calibre"
                        else:
                            # One final ingest dir check (Stacks download may have just completed)
                            final_files = _ingest_ebook_files(exclude=pre_existing)
                            if final_files:
                                logger.info(f"[{job_id}] File appeared during Calibre wait: {final_files[0]}")
                                file_path = os.path.join(CWA_INGEST_PATH, final_files[0])
                                with open(file_path, "rb") as f:
                                    file_data = f.read()
                                os.remove(file_path)
                                job["status"] = "importing"
                                job["stage_detail"] = "Uploading to Calibre..."
                                book_id = await _upload_to_calibre(file_data, final_files[0])
                                if book_id is not None:
                                    job["book_id"] = book_id
                                    job["status"] = "done"
                                    job["message"] = "Added to Calibre"
                                    job["stage_detail"] = "Added to Calibre"
                                else:
                                    job["status"] = "done"
                                    job["message"] = "Uploaded — Calibre import may still be processing"
                                    job["stage_detail"] = job["message"]
                            else:
                                logger.warning(f"[{job_id}] Timeout waiting for file and not in Calibre — attempting direct download")
                                if await _try_direct_download(job_id, job, md5, title, author, detail):
                                    pass
                                else:
                                    job["status"] = "failed"
                                    job["code"] = "no_route"
                                    job["message"] = "All download methods failed"
                                    job["stage_detail"] = job["message"]
                        return

            # File is in ingest dir — read it, upload via HTTP, clean up
            file_path = os.path.join(CWA_INGEST_PATH, job.get("filename", ""))
            if file_path and os.path.isfile(file_path):
                with open(file_path, "rb") as f:
                    file_data = f.read()
                os.remove(file_path)
                job["status"] = "importing"
                job["stage_detail"] = "Uploading to Calibre..."
                book_id = await _upload_to_calibre(file_data, job["filename"])
            else:
                # Fallback: file path lost, try OPDS
                job["status"] = "importing"
                job["stage_detail"] = "Checking Calibre..."
                book_id = await _wait_for_calibre(title, timeout=60)

        # Final status
        if job["status"] != "done":
            if job.get("book_id") or (book_id is not None):
                if not job.get("book_id"):
                    job["book_id"] = book_id
                job["status"] = "done"
                job["message"] = "Added to Calibre"
                job["stage_detail"] = "Added to Calibre"
            else:
                job["status"] = "done"
                job["message"] = "Uploaded — Calibre import may still be processing"
                job["stage_detail"] = job["message"]

    except CalibreUnreachable as e:
        # From the Stacks routes, which call _upload_to_calibre directly.
        job["status"] = "failed"
        job["code"] = "calibre_down"
        job["message"] = job["stage_detail"] = (
            f"Calibre-Web is unreachable ({e}), so nothing could be added. "
            "Share it again once Calibre is back")
    except Exception as e:
        job["status"] = "failed"
        job["code"] = "unexpected"
        job["message"] = f"Unexpected error: {e}"
        job["stage_detail"] = job["message"]
        logger.exception(f"[{job_id}] Download failed for {md5}")
    finally:
        # Always sweep stragglers — the upload path os.removes the file it consumed,
        # so anything still here under our pre_existing diff is a duplicate Stacks
        # delivery, a partial download, or an unrelated arrival. Leaving it would
        # poison the next job (this is exactly how the wrong-book-emailed bug
        # manifested before the snapshot was added).
        _cleanup_unconsumed_ingest_files(job_id, pre_existing)
        # The Kindle send, the outcome and the Slack line all happen in
        # _settle_job, the single point where a share ends: the early `return`
        # paths above set status before exiting and still arrive here.
        try:
            await _settle_job(job_id, title)
        except Exception:
            logger.exception(f"[{job_id}] Settling the job failed")
            _mark_finished(job_id)
        finally:
            # Fire-and-forget, so it survives early returns too (the previous
            # awaited sleep at function-tail was skipped on early return paths
            # and leaked job state for ~10 minutes).
            asyncio.create_task(_ttl_cleanup_job(job_id))


async def _settle_job(job_id: str, title: str | None = None) -> None:
    """End a share with one answer.

    The order is the point. The Kindle step runs inside its own guard, so an
    exception there still ends the job. Then the outcome is decided once, the
    job is marked finished (which answers a waiting phone at once), and only
    after that is Slack told, so a slow webhook never delays the phone.
    """
    job = _download_jobs.get(job_id)
    if job is None or job.get("finished"):
        # Already answered, e.g. reported lost while the pod was stopping.
        return
    # The job's own title first: a bare md5 share starts as "Unknown" and
    # learns its real name from the library.
    title = job.get("title") or title or ""
    try:
        await _maybe_send_to_kindle(job_id, title)
    except Exception as e:
        logger.exception(f"[{job_id}] Kindle step failed")
        job["status"] = "failed"
        job["code"] = "unexpected"
        job["reason"] = f"the Kindle step failed unexpectedly ({type(e).__name__})"
        job["message"] = job["stage_detail"] = f"Unexpected error in the Kindle step: {e}"
    job["outcome"], reason = _decide_outcome(job)
    if reason:
        job["reason"] = reason
    job["finished_at"] = time.time()
    if job.get("rescue_of"):
        # A retry or an agent's job: it answers to the parent's rescue, not to
        # Slack, and never opens a rescue of its own.
        job["final_text"] = _outcome_line(job, markup=False)
        _mark_finished(job_id)
        await _child_settled(job_id, job)
        return
    slack_note, phone_note = await _open_rescue(job_id, job) if _rescue_eligible(job) else ("", "")
    job["final_text"] = _outcome_line(job, markup=False) + (f" {phone_note}" if phone_note else "")
    _mark_finished(job_id)
    _journal_remove(job_id)
    await _post_slack(_outcome_line(job, markup=True) + (f" {slack_note}" if slack_note else ""))


async def _maybe_send_to_kindle(job_id: str, title: str) -> None:
    """If the job carried a kindle_email and successfully imported a book, send
    the file via SMTP (with retry). On exhausted retries, mark the job failed
    so the caller (iOS Shortcut, integrations) sees a real error instead of a
    misleading 'Added to Calibre' success."""
    job = _download_jobs.get(job_id)
    if not job:
        return
    kindle_email = job.get("kindle_email")
    if not (kindle_email and job.get("status") == "done"):
        return
    # Once per job, whoever calls. The early-return paths used to call this and
    # then the finally block called it again, so Anca's Kindle got the same book
    # twice, two seconds apart. Removing those calls fixed it; this makes a
    # future one harmless rather than silently doubling the email.
    if job.get("kindle_attempted"):
        logger.info("[%s] Kindle send already attempted, not repeating", job_id)
        return
    job["kindle_attempted"] = True
    bid = job.get("book_id") or 0
    looked = job.get("code") == "calibre_id"  # the upload step looked and gave up
    if bid > 0 and not job.get("book_id_confirmed"):
        # An id no upload step checked, such as one the Stacks routes took
        # straight from an OPDS search. Confirm it before emailing anything.
        bid = await _confirm_calibre_id(job, job.get("title") or title,
                                        job.get("author") or "", bid) or 0
        looked = True
    if bid <= 0:
        # A last look at the library, then say so. Returning quietly here is
        # what made a job report "Added to Calibre" while the Kindle got
        # nothing — the caller had no way to tell delivery had not happened.
        if not looked:
            job["phase"] = "importing"
            also = [tuple(job["file_meta"])] if job.get("file_meta") else []
            bid = await _resolve_calibre_id(
                job.get("title") or title, job.get("author") or "", also=also,
                newer_than=job.get("library_max_id"),
            ) or 0
        if bid <= 0:
            job["status"] = "failed"
            job["code"] = "calibre_id"
            job["reason"] = ("it reached Calibre but could not be found in the library, "
                             "so it was not emailed. Send it from Calibre by hand")
            job["message"] = (
                "Added to Calibre but could not identify the book in the library, "
                "so it was not sent to the Kindle. Send it by hand from Calibre."
            )
            job["stage_detail"] = job["message"]
            logger.warning(
                "[%s] No Calibre id for %r; skipping Kindle send to %s",
                job_id, title, kindle_email,
            )
            return
    job["book_id"] = bid
    job["book_id_confirmed"] = True
    job["phase"] = "sending"
    job["stage_detail"] = "Sending to Kindle..."
    err = await _send_to_kindle(bid, title, kindle_email)
    if isinstance(err, AlreadySent):
        # Not a failure: the book is already on that Kindle.
        job["kindle_already_sent"] = True
        job["kindle_sent_at"] = err.at
        job["message"] = f"Added to Calibre; {err}, so not sending it twice"
    elif err:
        job["status"] = "failed"
        job["code"] = "kindle_smtp"
        job["kindle_error"] = err
        job["reason"] = f"the email did not go through ({err})"
        job["message"] = f"Added to Calibre but failed to send to Kindle after retries: {err}"
    else:
        job["kindle_sent"] = True
        job["message"] = f"Added to Calibre and sent to {kindle_email}"
    job["stage_detail"] = job["message"]


async def _ttl_cleanup_job(job_id: str) -> None:
    """Drop the job from the in-memory state after JOB_TTL_SECONDS so /api/download-status
    eventually 404s and the dict doesn't grow without bound.

    A job marked `held` stays until the hold is lifted.
    """
    await asyncio.sleep(JOB_TTL_SECONDS)
    while (_download_jobs.get(job_id) or {}).get("held"):
        await asyncio.sleep(60)
    _download_jobs.pop(job_id, None)
    _job_events.pop(job_id, None)


