# In-memory job store for async downloads. A running job also leaves a journal
# file (see _journal_write), so a restart that kills it is still reported.
_download_jobs: dict[str, dict] = {}
# A finished job stays readable this long, so a phone that asks late still
# gets its answer.
JOB_TTL_SECONDS = 1800
# Phones waiting on a job. Kept apart from the job, whose dict is returned as
# JSON by /api/download-status/{job_id}.
_job_events: dict[str, asyncio.Event] = {}


def _write_json_atomic(path: str, data) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    temp = f"{path}.{uuid.uuid4().hex[:8]}.tmp"
    with open(temp, "w") as f:
        json.dump(data, f)
    os.replace(temp, path)


def _journal_file(job_id: str) -> str:
    return os.path.join(STATE_DIR, "jobs", f"{job_id}.json")


def _journal_write(job_id: str, job: dict) -> None:
    """Note a running job on disk. Never raises: a job must not fail over this."""
    entry = {k: job.get(k) for k in ("title", "author", "md5", "kindle_email", "created_at")}
    entry.update(job_id=job_id, pod=socket.gethostname())
    try:
        _write_json_atomic(_journal_file(job_id), entry)
    except OSError as e:
        logger.warning(f"[{job_id}] Could not write the job journal: {e}")


def _journal_remove(job_id: str) -> None:
    try:
        os.remove(_journal_file(job_id))
    except FileNotFoundError:
        pass
    except OSError as e:
        logger.warning(f"[{job_id}] Could not remove the job journal entry: {e}")


def _journal_heartbeat() -> None:
    """Touch every running job's entry, so no other pod takes it for lost."""
    now = time.time()
    for job_id, job in list(_download_jobs.items()):
        if job.get("finished") or not job.get("md5"):
            continue
        try:
            os.utime(_journal_file(job_id), (now, now))
        except OSError:
            pass


def _mark_finished(job_id: str) -> None:
    """Settle a job for anyone asking, and wake a phone that is waiting on it."""
    job = _download_jobs.get(job_id)
    if job is not None:
        job["finished"] = True
        job.setdefault("finished_at", time.time())
    event = _job_events.get(job_id)
    if event is not None:
        event.set()


def _tombstone(text: str, code: str, outcome: str = "rejected", **fields) -> str:
    """A job that is over before it starts, so a share that was turned away
    still has an id whose waits repeat the real reason."""
    job_id = fields.pop("job_id", None) or uuid.uuid4().hex[:12]
    now = time.time()
    job = {"status": "failed", "title": "", "author": "", "md5": None,
           "kindle_email": None, "created_at": now}
    job.update(fields)
    job.update(outcome=outcome, code=code, reason=text or None, finished=True, finished_at=now)
    job["final_text"] = text or _outcome_line(job, markup=False)
    job["message"] = job["stage_detail"] = job["final_text"]
    _download_jobs[job_id] = job
    asyncio.create_task(_ttl_cleanup_job(job_id))
    return job_id


async def _recover_lost_jobs() -> int:
    """Report the jobs a pod that is gone left behind: one Slack line each.

    An entry counts as abandoned once nothing has touched it for
    JOURNAL_STALE_SECONDS; during a rolling update the old pod keeps its own
    entries fresh until it stops. Renaming the file first claims it, so two
    pods never both report one job.
    """
    folder = os.path.join(STATE_DIR, "jobs")
    try:
        names = os.listdir(folder)
    except OSError:
        return 0
    reported = 0
    now = time.time()
    for name in names:
        if not name.endswith(".json"):
            continue
        job_id = name[: -len(".json")]
        mine = _download_jobs.get(job_id)
        if mine is not None and not mine.get("finished"):
            continue
        path = os.path.join(folder, name)
        try:
            if now - os.path.getmtime(path) < JOURNAL_STALE_SECONDS:
                continue
            claimed = f"{path}.{uuid.uuid4().hex[:6]}.claimed"
            os.rename(path, claimed)
        except OSError:
            continue
        try:
            with open(claimed) as f:
                entry = json.load(f)
        except (OSError, ValueError):
            entry = {}
        finally:
            try:
                os.remove(claimed)
            except OSError:
                pass
        _tombstone("", "lost_restart", outcome="lost", job_id=job_id,
                   title=entry.get("title") or "", author=entry.get("author") or "",
                   md5=None, kindle_email=entry.get("kindle_email"))
        logger.warning(f"[{job_id}] Found a job lost in a restart: {entry.get('title')!r}")
        await _post_slack(_outcome_line(_download_jobs[job_id], markup=True))
        reported += 1
    return reported


async def _report_jobs_lost_on_shutdown() -> None:
    """Called as the pod stops: every job still running is about to die with it."""
    for job_id, job in list(_download_jobs.items()):
        if job.get("finished") or not job.get("md5") or job.get("rescue_of"):
            # A rescue's retry is started again by the next pod's rescue loop.
            continue
        if job.get("phase") == "sending":
            # Most likely done within the grace period; if not, its journal
            # entry goes stale and the next pod reports it.
            continue
        job["outcome"] = "lost"
        job["code"] = "lost_restart"
        job["final_text"] = _outcome_line(job, markup=False)
        _mark_finished(job_id)
        _journal_remove(job_id)
        await _post_slack(_outcome_line(job, markup=True))


async def _periodic_journal():
    while True:
        try:
            _journal_heartbeat()
            await _recover_lost_jobs()
        except Exception as e:
            logger.warning(f"Job journal sweep failed: {e}")
        await asyncio.sleep(JOURNAL_HEARTBEAT_SECONDS)


def _build_search_terms(title: str) -> list[str]:
    """Build a list of progressively simpler search terms from a title."""
    base = title.split("—")[0].split("-")[0].strip()[:50]
    terms = []
    if base and base.replace("\u2019", "'") not in ("Unknown", "Anna's Archive", "Anna\u2019s Archive"):
        terms.append(base)
        # Try last significant word (often the actual book name)
        words = [w for w in _re.split(r'\s+', base) if len(w) > 3 and w.upper() != w[:1].upper() + w[1:].lower() or len(w) > 4]
        if words and words[-1].lower() != base.lower():
            terms.append(words[-1])
    return terms


async def _opds_search(client: httpx.AsyncClient, term: str) -> int | None:
    """Single OPDS search attempt. Returns Calibre book ID or None."""
    import xml.etree.ElementTree as ET
    try:
        r = await client.get(f"{CALIBRE_WEB_URL}/opds/search/{term}")
        if r.status_code == 200:
            ns = {'atom': 'http://www.w3.org/2005/Atom'}
            entries = ET.fromstring(r.text).findall('.//atom:entry', ns)
            if entries:
                # Extract book_id from OPDS download link: /opds/download/<id>/epub/
                for link in entries[0].findall('atom:link', ns):
                    href = link.get('href', '')
                    m = _re.search(r'/opds/download/(\d+)/', href)
                    if m:
                        return int(m.group(1))
                return -1  # found but couldn't extract ID
    except Exception:
        pass
    return None


async def _wait_for_calibre(title: str, timeout: int = 120) -> int | None:
    """Poll Calibre-Web OPDS until the book appears or timeout.

    Returns Calibre book ID on success, None on timeout.
    Tries progressively simpler search terms to handle mismatched titles.
    """
    search_terms = _build_search_terms(title)
    if not search_terms:
        drained = await _wait_for_ingest_drain(timeout)
        return -1 if drained else None

    async with httpx.AsyncClient(timeout=5, follow_redirects=True) as client:
        elapsed = 0
        # Try primary term for first 2/3 of timeout
        primary_budget = min(timeout * 2 // 3, timeout - 6) if len(search_terms) > 1 else timeout
        while elapsed < primary_budget:
            book_id = await _opds_search(client, search_terms[0])
            if book_id is not None:
                return book_id
            await asyncio.sleep(3)
            elapsed += 3

        # Try fallback terms for remaining time
        for term in search_terms[1:]:
            logger.info(f"OPDS: primary term failed, trying fallback '{term}'")
            while elapsed < timeout:
                book_id = await _opds_search(client, term)
                if book_id is not None:
                    return book_id
                await asyncio.sleep(3)
                elapsed += 3
    return None


class CalibreUnreachable(Exception):
    """Calibre-Web could not take any upload: down, erroring, or refusing our login.

    Kept apart from a refusal of one file because another file cannot help.
    A job that sees this stops downloading and starts no rescue.
    """


async def _upload_to_calibre(file_data: bytes, filename: str) -> int | None:
    """Upload book to CWA via HTTP.

    Returns -1 when Calibre-Web accepted the file, None when it refused this
    file, and raises CalibreUnreachable when it could not take any file at all.
    The id is for the caller to find in the library (_confirm_calibre_id).
    This used to poll OPDS for up to 60 s for one, with a search whose first
    term is the author, and on 2026-09-24 that search named Bill Perkins's Die
    with Zero for The Yellow Wallpaper.
    """
    import re
    try:
        async with httpx.AsyncClient(timeout=30, follow_redirects=True) as client:
            if not await _cwa_login(client):
                raise CalibreUnreachable("its login failed")

            # GET / → extract fresh CSRF token for upload
            r = await client.get(f"{CALIBRE_WEB_URL}/")
            if r.status_code != 200:
                raise CalibreUnreachable(f"its home page answered {r.status_code}")
            m = re.search(r'name="csrf_token"\s+value="([^"]+)"', r.text)
            if not m:
                raise CalibreUnreachable("its home page carried no CSRF token")
            csrf = m.group(1)

            # POST /upload with multipart form
            files = {"btn-upload": (filename, file_data)}
            data = {"csrf_token": csrf}
            r = await client.post(f"{CALIBRE_WEB_URL}/upload", data=data, files=files)
            if r.status_code >= 500:
                raise CalibreUnreachable(f"its upload answered {r.status_code}")
            if r.status_code != 200:
                logger.warning(f"CWA upload: /upload returned {r.status_code} for {filename}")
                return None

            # Check for success response
            try:
                resp_json = r.json()
            except Exception:
                resp_json = None
                logger.info(f"CWA upload: uploaded {filename} (non-JSON response)")
            if resp_json is not None:
                if resp_json.get("location") != "/tasks":
                    # Refused: it sends the browser back to "/" with a flashed
                    # error and queues nothing. Polling OPDS after this is what
                    # made a job report "Added to Calibre" for a Moby-Dick PDF
                    # that libmagic did not recognise (2026-09-24).
                    logger.warning(f"CWA upload: Calibre-Web refused {filename}: {resp_json}")
                    return None
                logger.info(f"CWA upload: successfully uploaded {filename}")

    except CalibreUnreachable as e:
        logger.warning(f"CWA upload: Calibre-Web unreachable for {filename}: {e}")
        raise
    except httpx.HTTPError as e:
        logger.warning(f"CWA upload: Calibre-Web unreachable for {filename}: {type(e).__name__}: {e}")
        raise CalibreUnreachable(f"{type(e).__name__}") from e
    except Exception as e:
        logger.exception(f"CWA upload failed for {filename}: {e}")
        return None

    return -1


EBOOK_EXTENSIONS = ('.epub', '.pdf', '.mobi', '.azw3', '.djvu', '.cbz', '.cbr', '.fb2')

# Calibre-Web's upload handler drops each file into the ingest folder as
# new_<user>_<YYYYMMDD>_<HHMMSS>_<micro>_<name>, or format_<book>_... for an extra
# format (cps/editbooks.py _get_ingest_path), and imports it from there. Calibre
# owns the file until the import finishes and removes it itself afterwards.
# Deleting one mid-import is what lost Remember Me on 2026-09-24.
_CWA_UPLOAD_RE = _re.compile(r"^(?:new|format)_\d+_\d{8}_\d{6}_\d{6}_")


def _is_cwa_upload(filename: str) -> bool:
    return bool(_CWA_UPLOAD_RE.match(filename)) and filename.lower().endswith(EBOOK_EXTENSIONS)


def _cwa_uploads_pending() -> list[str]:
    """Calibre-Web uploads still in the ingest folder, i.e. not imported yet."""
    try:
        return [f for f in os.listdir(CWA_INGEST_PATH) if _is_cwa_upload(f)]
    except OSError:
        return []


def _invalid_ingest_reason(filename: str, full_path: str) -> str | None:
    """Return a human-readable reason if `filename` looks like a poisoned ingest
    file (Stacks integrity-mismatch leftover, AA rate-limit stub, etc), or None
    if it looks like a real ebook. Filename check is case-insensitive."""
    if ".mismatch" in filename.lower():
        return "MISMATCH suffix (Stacks integrity check failed)"
    try:
        size = os.path.getsize(full_path)
    except OSError as e:
        return f"unreadable ({e})"
    if size < MIN_EBOOK_SIZE_BYTES:
        return f"size {size}B below minimum {MIN_EBOOK_SIZE_BYTES}B"
    return None


def _ingest_ebook_files(exclude: set[str] | None = None) -> list[str]:
    """List valid ebook files in the ingest directory.

    Skips: non-ebook extensions, files in `exclude` (callers snapshot this set
    before queueing so orphans from prior jobs are ignored), files rejected by
    `_invalid_ingest_reason` (MISMATCH, too small), and Calibre-Web's own
    uploads, which are never a download and which callers would re-upload and
    delete while Calibre is importing them.
    """
    exclude = exclude or set()
    try:
        names = os.listdir(CWA_INGEST_PATH)
    except OSError:
        return []
    out = []
    for f in names:
        if f in exclude or _is_cwa_upload(f):
            continue
        full = os.path.join(CWA_INGEST_PATH, f)
        if not os.path.isfile(full):
            continue
        if not any(f.lower().endswith(e) for e in EBOOK_EXTENSIONS):
            continue
        if _invalid_ingest_reason(f, full):
            continue
        out.append(f)
    return out


def _cleanup_unconsumed_ingest_files(job_id: str, pre_existing: set[str]) -> list[str]:
    """At end-of-job, sweep any ebook files that arrived in the ingest dir during
    the job but weren't consumed (uploaded + os.removed) by it. Avoids leaking
    partial downloads or extra files (e.g. when Stacks delivers a duplicate)
    that would poison subsequent jobs. Files present *before* the job started
    (`pre_existing`) are left alone — they belong to a different job, and so
    are Calibre-Web's own uploads, which Calibre may still be importing."""
    try:
        cur = set(os.listdir(CWA_INGEST_PATH))
    except OSError:
        return []
    removed = []
    for f in cur - pre_existing:
        full = os.path.join(CWA_INGEST_PATH, f)
        if not os.path.isfile(full):
            continue
        if not any(f.lower().endswith(e) for e in EBOOK_EXTENSIONS):
            continue
        if _is_cwa_upload(f):
            logger.info(f"[{job_id}] Leaving {f} to Calibre, which is still importing it")
            continue
        try:
            os.remove(full)
            removed.append(f)
            logger.warning(f"[{job_id}] Cleaned up unconsumed ingest file: {f}")
        except OSError as e:
            logger.warning(f"[{job_id}] Failed to clean unconsumed file {f}: {e}")
    return removed


def _sweep_ingest_orphans() -> list[str]:
    """Delete invalid ebook files (MISMATCH leftovers, tiny stubs) from the ingest
    directory. Returns the list of filenames removed. Callers should invoke this
    at the start of each download job so a leaked file from a prior failure
    cannot be picked up as the current job's payload."""
    try:
        names = os.listdir(CWA_INGEST_PATH)
    except OSError:
        return []
    removed = []
    for f in names:
        full = os.path.join(CWA_INGEST_PATH, f)
        if not os.path.isfile(full):
            continue
        if not any(f.lower().endswith(e) for e in EBOOK_EXTENSIONS):
            continue
        reason = _invalid_ingest_reason(f, full)
        if not reason:
            continue
        try:
            os.remove(full)
            removed.append(f)
            logger.warning(f"Swept orphan ingest file {f}: {reason}")
        except OSError as e:
            logger.warning(f"Failed to sweep orphan {f}: {e}")
    return removed


def _fix_ingest_permissions():
    """Fix permissions on all files in ingest dir right now."""
    try:
        if os.path.isdir(CWA_INGEST_PATH):
            for entry in os.scandir(CWA_INGEST_PATH):
                if entry.is_file():
                    st = entry.stat()
                    if st.st_uid != CWA_UID or st.st_gid != CWA_GID or st.st_mode & 0o777 != 0o664:
                        _chown_for_cwa(entry.path)
                        logger.info(f"Fixed permissions on {entry.name}")
    except Exception as e:
        logger.warning(f"Permission fix error: {e}")


async def _wait_for_file_in_ingest(
    timeout: int = 90,
    exclude: set[str] | None = None,
    poll_interval: float = 3,
) -> str | None:
    """Wait for a NEW ebook file to appear in the ingest directory.

    Pass `exclude` (set of filenames present *before* queueing) so files from
    prior jobs aren't returned. `poll_interval` is overridable for tests.
    """
    iters = max(1, int(timeout / poll_interval))
    for _ in range(iters):
        files = _ingest_ebook_files(exclude=exclude)
        if files:
            return files[0]
        await asyncio.sleep(poll_interval)
    return None


async def _wait_for_file_in_ingest_or_stacks_fail(
    md5: str,
    timeout: int = 90,
    exclude: set[str] | None = None,
    poll_interval: float = 3,
) -> tuple[str | None, bool]:
    """Wait for a NEW ebook file to appear in the ingest directory OR Stacks
    reports failure. Returns (filename, stacks_failed). `exclude` filters out
    pre-existing files (orphans) so they aren't mistaken for the new download.
    """
    iters = max(1, int(timeout / poll_interval))
    for _ in range(iters):
        files = _ingest_ebook_files(exclude=exclude)
        if files:
            return files[0], False

        try:
            stacks_status = await annas_scraper.get_stacks_status()
            if stacks_status.get("available"):
                for item in stacks_status.get("recent_history", []):
                    if item.get("md5") == md5 and item.get("status") == "failed":
                        logger.warning(f"Stacks reported download failure for {md5}: {item.get('error', 'unknown')}")
                        return None, True
        except Exception as e:
            logger.warning(f"Failed to check Stacks status during wait: {e}")

        await asyncio.sleep(poll_interval)
    return None, False


async def _wait_for_ingest_drain(timeout: int = 120) -> bool:
    """Wait until the ingest folder has no ebook files (CWA consumed them)."""
    for _ in range(timeout // 3):
        try:
            files = [f for f in os.listdir(CWA_INGEST_PATH)
                     if os.path.isfile(os.path.join(CWA_INGEST_PATH, f))
                     and any(f.lower().endswith(e) for e in EBOOK_EXTENSIONS)]
            if not files:
                return True
        except OSError:
            pass
        await asyncio.sleep(3)
    return False


