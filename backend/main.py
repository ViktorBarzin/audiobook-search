@app.post("/api/send-to-kindle")
async def send_to_kindle(request: Request):
    """Send a book from Calibre to a Kindle email address.

    Only configured recipients: KINDLE_RECIPIENTS (by address, or by name in
    `deliver_to`) and the Goodreads address. A repeat within 24 hours is a 409.
    """
    _verify_api_key(request)
    data = await request.json()
    kindle_email = (data.get("kindle_email") or "").strip()
    deliver_to = (data.get("deliver_to") or "").strip().lower()
    if not kindle_email and deliver_to:
        kindle_email = KINDLE_RECIPIENTS.get(deliver_to, "")
    if not kindle_email:
        raise HTTPException(status_code=400, detail="kindle_email (or a known deliver_to) is required")
    allowed = {a.lower() for a in KINDLE_RECIPIENTS.values()} | {GOODREADS_KINDLE_EMAIL.lower()}
    allowed.discard("")
    if kindle_email.lower() not in allowed:
        raise HTTPException(status_code=400, detail="kindle_email is not one of the configured recipients")

    book_id = data.get("book_id")
    title = data.get("title", "Book")
    job_id = data.get("job_id")

    if not book_id and job_id:
        job = _download_jobs.get(job_id)
        if not job:
            raise HTTPException(status_code=404, detail="Job not found")
        book_id = job.get("book_id")
        title = job.get("title", title)
        if not book_id:
            raise HTTPException(status_code=400, detail="Job has no book_id yet (download may still be in progress)")

    if not book_id or book_id < 1:
        raise HTTPException(status_code=400, detail="book_id is required (provide book_id or job_id of a completed download)")

    err = await _send_to_kindle(book_id, title, kindle_email)
    if isinstance(err, AlreadySent):
        raise HTTPException(status_code=409, detail=f"Not sent: {err}")
    if err:
        raise HTTPException(status_code=500, detail=f"Failed to send: {err}")
    return {"status": "ok", "message": f"Sent to {kindle_email}"}


async def _add_to_shelf(client: httpx.AsyncClient, shelf_id: int, book_id: int) -> str | None:
    """Put an imported book on a calibre-web shelf. Returns an error string or None.

    CWA gates this on check_shelf_edit_permissions: a *public* shelf is writable by
    any account with the edit-shelves role, so the admin session used everywhere
    else here can add to a shelf owned by another user without their password.
    """
    r = await client.get(f"{CALIBRE_WEB_URL}/")
    if r.status_code != 200:
        return f"GET / returned {r.status_code}"
    m = _re.search(r'name="csrf_token"\s+value="([^"]+)"', r.text)
    if not m:
        return "no CSRF token"

    r = await client.post(
        f"{CALIBRE_WEB_URL}/shelf/add/{shelf_id}/{book_id}",
        data={"csrf_token": m.group(1)},
        headers={"X-Requested-With": "XMLHttpRequest", "X-CSRFToken": m.group(1)},
    )
    # Verified live: CWA answers 204 No Content on success, not 200.
    if 200 <= r.status_code < 300:
        return None
    # CWA answers 400 when the book is already on the shelf, which is not a failure
    # for an idempotent pipeline that may retry.
    if r.status_code == 400 and "already part of the shelf" in r.text.lower():
        return None
    return f"shelf/add returned {r.status_code}: {r.text[:120]}"


@app.post("/api/goodreads/ingest")
async def goodreads_ingest(request: Request):
    """Fetch one already-matched book by md5, import it, and shelve it.

    The Goodreads poller runs in its own pod and owns the decision of *what* to
    fetch; this endpoint owns the mechanics, because the ingest directory, the CWA
    session and the Calibre library are all already mounted and working here.
    """
    _verify_api_key(request)
    data = await request.json()

    md5 = (data.get("md5") or "").lower()
    title = data.get("title") or "Unknown"
    author = data.get("author") or "Unknown Author"
    shelf_id = int(data.get("shelf_id") or GOODREADS_SHELF_ID or 0)

    if not _re.fullmatch(r"[a-f0-9]{32}", md5):
        raise HTTPException(status_code=400, detail="a 32-character md5 is required")

    if not libgen_scraper:
        raise HTTPException(status_code=503, detail="LibGen scraper not available")

    try:
        await _check_cwa_duplicate(title, author)
    except HTTPException as e:
        if e.status_code == 409:
            return {"status": "duplicate", "message": str(e.detail)}
        raise

    file_data, filename = await libgen_scraper.download_file(md5)
    if not file_data:
        raise HTTPException(status_code=502, detail=f"download failed for md5 {md5}")

    reason = _invalid_ingest_reason(filename or "", "")
    if not filename or (reason and "size" not in reason):
        ext = ".pdf" if file_data[:4] == b"%PDF" else ".epub"
        filename = f"{author} - {title}{ext}"

    if len(file_data) < MIN_EBOOK_SIZE_BYTES:
        raise HTTPException(
            status_code=502,
            detail=f"downloaded file is only {len(file_data)} bytes — refusing to import",
        )

    try:
        uploaded = await _upload_to_calibre(file_data, filename)
    except CalibreUnreachable as e:
        raise HTTPException(status_code=502, detail=f"Calibre is unreachable: {e}")
    if not uploaded:
        raise HTTPException(status_code=502, detail="Calibre upload failed")

    # The id returned by _upload_to_calibre comes from a fuzzy OPDS search whose
    # fallback term is a single word, so it can name a book that was already in
    # the library: fetching Neuromancer once resolved to a CISSP study guide
    # co-authored by a different Gibson, which was then shelved. The library
    # database is the authority here — matched on title AND author — and no id
    # at all is a better outcome than a confident wrong one.
    book_id = None
    for _ in range(12):  # ~2 minutes; a large import may still be committing
        book_id = _calibre_id_for(title, author)
        if book_id:
            break
        await asyncio.sleep(10)

    if book_id:
        logger.info(f"Resolved Calibre id {book_id} for {title!r} from the library")
    else:
        logger.warning(
            f"Imported {title!r} but could not identify it in the library; not shelving"
        )
        book_id = -1

    shelf_error = None
    if shelf_id and book_id > 0:
        async with httpx.AsyncClient(timeout=30, follow_redirects=True) as client:
            if await _cwa_login(client):
                shelf_error = await _add_to_shelf(client, shelf_id, book_id)
            else:
                shelf_error = "CWA login failed"
        if shelf_error:
            logger.warning(f"Shelf add failed for book {book_id}: {shelf_error}")

    # Forward to the Kindle, which is the point of the shelf for her. Reported
    # back in three separate fields because "we chose not to send this" and "the
    # send broke" mean different things to whoever reads the Slack line: only the
    # second one needs a person. Either way the book is already in Calibre and on
    # the shelf, so nothing here is allowed to fail the ingest.
    kindle_sent = False
    kindle_error = None
    kindle_skipped = None

    if not GOODREADS_KINDLE_EMAIL:
        kindle_skipped = "no Kindle address configured"
    elif book_id <= 0:
        kindle_skipped = "not identified in the library, so it cannot be fetched to send"
    else:
        formats = _calibre_formats_for(book_id)
        fmt, kindle_skipped = choose_kindle_format(formats, sizes=formats)
        if fmt:
            result = await _send_to_kindle(
                book_id, title, GOODREADS_KINDLE_EMAIL, formats=(fmt,),
            )
            if isinstance(result, AlreadySent):
                # Delivered before, by this path or another: a skip, not a failure.
                kindle_skipped = str(result)
            else:
                kindle_error = result
                kindle_sent = result is None
            if kindle_error:
                logger.warning(
                    f"Kindle send failed for book {book_id} ({title!r}): {kindle_error}"
                )

    # No Slack post from here. The poller announces every outcome itself, with
    # the match reason and the shelf, and its contract is exactly one line per
    # book — this endpoint posting as well made that two, which was already the
    # case before Kindle forwarding and would now have said "Kindle" twice.
    # backend/goodreads/sync.py owns the message for this pipeline.

    return {
        "status": "ok",
        "book_id": book_id,
        "filename": filename,
        "bytes": len(file_data),
        "shelf_error": shelf_error,
        "kindle_sent": kindle_sent,
        "kindle_error": kindle_error,
        "kindle_skipped": kindle_skipped,
    }


