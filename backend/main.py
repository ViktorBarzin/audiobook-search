async def _download_ebook(req: DownloadRequest, author: str, title: str):
    """Handle ebook downloads — route to CWA ingest folder via Stacks or direct download."""
    # Check CWA for duplicates (unless force)
    if not req.force:
        await _check_cwa_duplicate(title, author)

    if req.source in ("annas", "libgen"):
        # Extract MD5 for Stacks download
        md5 = None
        if req.source == "annas":
            md5_match = _re.search(r"/md5/([a-f0-9]+)", req.magnet_url, _re.IGNORECASE)
            if md5_match:
                md5 = md5_match.group(1)
        elif req.source == "libgen":
            md5_match = _re.search(r"md5=([a-f0-9]+)", req.magnet_url, _re.IGNORECASE)
            if not md5_match:
                md5_match = _re.search(r"/main/([a-f0-9]+)", req.magnet_url, _re.IGNORECASE)
            if md5_match:
                md5 = md5_match.group(1)

        # Try direct download first (faster, more reliable than Stacks)
        if req.source == "annas" and annas_scraper:
            try:
                file_data, filename = await annas_scraper.download_file(req.magnet_url)
                if file_data:
                    if not filename:
                        ext = ".epub"
                        if file_data[:4] == b"%PDF":
                            ext = ".pdf"
                        filename = f"{author} - {title}{ext}"
                    save_path = _publish_ingest_file(file_data, filename)
                    logger.info(f"Ebook saved to CWA ingest: {save_path}")
                    return {"status": "ok", "message": f"Ebook saved → Calibre Library ({filename})"}
            except Exception as e:
                logger.warning(f"Direct download failed: {e}")

        # LibGen direct: AA's md5 IS libgen's md5, so an Anna's-Archive pick can be
        # fetched from the libgen mirror AA itself links. Preferred over Stacks —
        # AA's own /slow_download/ now serves a challenge FlareSolverr times out on
        # and /fast_download/ is paid, so every Stacks attempt since 2026-05-01 has
        # failed. This path needs no challenge solving.
        if md5 and libgen_scraper:
            try:
                file_data, filename = await libgen_scraper.download_file(md5)
                if file_data:
                    save_path = _publish_ingest_file(file_data, filename)
                    logger.info(f"Ebook saved to CWA ingest via libgen: {save_path}")
                    return {"status": "ok",
                            "message": f"Ebook saved → Calibre Library ({filename})"}
            except Exception as e:
                logger.warning(f"LibGen direct download failed: {e}")

        # Fallback: try Stacks (async queue, file lands in shared NFS)
        if md5 and annas_scraper:
            stacks_result = await annas_scraper.download_via_stacks(md5)
            if stacks_result.get("success"):
                return {"status": "ok", "message": stacks_result["message"]}
            logger.warning(f"Stacks download also failed: {stacks_result.get('error')}")

        if req.source == "annas":
            raise HTTPException(status_code=502, detail="All download methods failed for Anna's Archive")

        if req.source == "libgen":
            # LibGen: download from library.lol mirror
            try:
                async with httpx.AsyncClient(timeout=30.0, follow_redirects=True) as client:
                    # library.lol page has the actual download link
                    r = await client.get(req.magnet_url)
                    r.raise_for_status()
                    from bs4 import BeautifulSoup
                    soup = BeautifulSoup(r.text, "html.parser")
                    dl_link = soup.find("a", href=_re.compile(r"\.epub|\.pdf|\.mobi|cloudflare|get\.php", _re.IGNORECASE))
                    if dl_link:
                        dl_url = dl_link.get("href", "")
                        if not dl_url.startswith("http"):
                            dl_url = f"https://library.lol{dl_url}"
                        file_resp = await client.get(dl_url)
                        file_resp.raise_for_status()

                        filename = None
                        cd = file_resp.headers.get("content-disposition", "")
                        fname_match = _re.search(r'filename[*]?=["\']?([^"\';\n]+)', cd)
                        if fname_match:
                            filename = fname_match.group(1).strip()
                            # Validate extension
                            valid_ext = (".epub", ".pdf", ".mobi", ".azw3", ".djvu", ".cbz", ".cbr", ".fb2")
                            if not any(filename.lower().endswith(ext) for ext in valid_ext):
                                filename = None
                        if not filename:
                            ext = ".epub"
                            if file_resp.content[:4] == b"%PDF":
                                ext = ".pdf"
                            filename = f"{author} - {title}{ext}"

                        save_path = _publish_ingest_file(file_resp.content, filename)
                        logger.info(f"LibGen ebook saved to CWA ingest: {save_path}")
                        return {"status": "ok", "message": f"Ebook saved → Calibre Library ({filename})"}
                    else:
                        raise HTTPException(status_code=502, detail="Could not find download link on LibGen mirror page")
            except HTTPException:
                raise
            except Exception as e:
                raise HTTPException(status_code=502, detail=f"LibGen download failed: {e}")

    elif req.source == "mam":
        # MAM ebook: download .torrent → qBittorrent with CWA ingest path
        if not mam_scraper:
            raise HTTPException(status_code=500, detail="MAM scraper not configured")

        tid_match = _re.search(r"tid=(\d+)", req.magnet_url) or _re.search(r"/download\.php/(\d+)", req.magnet_url)
        if not tid_match:
            raise HTTPException(status_code=400, detail="Invalid MAM torrent URL")

        torrent_data = await mam_scraper.download_torrent_file(tid_match.group(1))
        if not torrent_data:
            raise HTTPException(status_code=502, detail="Failed to download .torrent file from MAM")

        async with httpx.AsyncClient(timeout=30.0) as client:
            await client.post(
                f"{QBITTORRENT_URL}/api/v2/auth/login",
                data={"username": QBITTORRENT_USER, "password": QBITTORRENT_PASS},
            )
            resp = await client.post(
                f"{QBITTORRENT_URL}/api/v2/torrents/add",
                files={"torrents": ("ebook.torrent", torrent_data, "application/x-bittorrent")},
                data={
                    "savepath": CWA_INGEST_PATH,
                    "category": "ebooks",
                    "tags": "mam",
                },
            )
            if resp.status_code != 200 or resp.text.strip().lower() != "ok.":
                raise HTTPException(status_code=502, detail=f"qBittorrent rejected torrent: {resp.text}")

        return {"status": "ok", "message": f"Ebook download started → Calibre Library"}

    elif req.source == "openlib":
        # Open Library: redirect to reading/borrowing page
        return {"status": "ok", "message": f"Open Library book — open in browser to borrow/read", "redirect": req.magnet_url}

    raise HTTPException(status_code=400, detail=f"Unsupported ebook source: {req.source}")


async def _download_audiobook(req: DownloadRequest, author: str, title: str):
    """Handle audiobook downloads — existing flow via qBittorrent → Audiobookshelf."""
    save_path = f"/audiobooks/{author}/{title}"

    # Check Audiobookshelf for duplicates (unless force)
    if not req.force and AUDIOBOOKSHELF_TOKEN:
        try:
            async with httpx.AsyncClient(timeout=15.0) as abs_client:
                libs_resp = await abs_client.get(
                    f"{AUDIOBOOKSHELF_URL}/api/libraries",
                    headers={"Authorization": f"Bearer {AUDIOBOOKSHELF_TOKEN}"},
                )
                for lib in libs_resp.json().get("libraries", []):
                    search_resp = await abs_client.get(
                        f"{AUDIOBOOKSHELF_URL}/api/libraries/{lib['id']}/search",
                        params={"q": title, "limit": 10},
                        headers={"Authorization": f"Bearer {AUDIOBOOKSHELF_TOKEN}"},
                    )
                    results = search_resp.json().get("book", [])
                    for item in results:
                        book_data = item.get("libraryItem", {}).get("media", {}).get("metadata", {})
                        if is_same_book(title, author, book_data.get("title"),
                                        book_data.get("authorName")):
                            raise HTTPException(
                                status_code=409,
                                detail=f"Book already exists in Audiobookshelf: '{book_data.get('title')}' by {book_data.get('authorName')}"
                            )
        except HTTPException:
            raise
        except Exception as e:
            logger.warning(f"Audiobookshelf duplicate check failed (proceeding anyway): {e}")

        # Audiobookshelf only knows about books it has already IMPORTED, so a
        # copy that is still downloading is invisible to the check above. That
        # is how two copies of "Principles for Dealing with the Changing World
        # Order" both landed on 2026-08-08 — they were queued back-to-back.
        inflight = await _find_inflight_audiobook(title, author)
        if inflight:
            raise HTTPException(
                status_code=409,
                detail=(f"Already downloading: '{inflight.get('name')}' "
                        f"({(inflight.get('progress') or 0) * 100:.0f}% complete)"),
            )

    is_mam_torrent = req.magnet_url.startswith("https://www.myanonamouse.net/")
    _prepare_audiobook_save_path(save_path)

    try:
        async with httpx.AsyncClient(timeout=30.0) as client:
            login_resp = await client.post(
                f"{QBITTORRENT_URL}/api/v2/auth/login",
                data={"username": QBITTORRENT_USER, "password": QBITTORRENT_PASS},
            )
            if login_resp.status_code != 200:
                raise HTTPException(status_code=502, detail=f"qBittorrent login failed: {login_resp.status_code}")

            if is_mam_torrent:
                if not mam_scraper:
                    raise HTTPException(status_code=500, detail="MAM scraper not configured")

                tid_match = _re.search(r"tid=(\d+)", req.magnet_url) or _re.search(r"/download\.php/(\d+)", req.magnet_url)
                if not tid_match:
                    raise HTTPException(status_code=400, detail="Invalid MAM torrent URL")

                torrent_data = await mam_scraper.download_torrent_file(tid_match.group(1))
                if not torrent_data:
                    raise HTTPException(status_code=502, detail="Failed to download .torrent file from MAM")

                resp = await client.post(
                    f"{QBITTORRENT_URL}/api/v2/torrents/add",
                    files={"torrents": ("audiobook.torrent", torrent_data, "application/x-bittorrent")},
                    data={
                        "savepath": save_path,
                        "category": "audiobooks",
                        "tags": "mam",
                    },
                )
            else:
                hash_match = _re.search(r"btih:([a-fA-F0-9]{40})", req.magnet_url)
                if hash_match:
                    info_hash = hash_match.group(1).lower()
                    await client.post(
                        f"{QBITTORRENT_URL}/api/v2/torrents/delete",
                        data={"hashes": info_hash, "deleteFiles": "false"},
                    )

                resp = await client.post(
                    f"{QBITTORRENT_URL}/api/v2/torrents/add",
                    data={
                        "urls": req.magnet_url,
                        "savepath": save_path,
                        "category": "audiobooks",
                    },
                )

            if resp.status_code != 200 or resp.text.strip().lower() != "ok.":
                raise HTTPException(status_code=502, detail=f"qBittorrent rejected torrent: {resp.text}")

        asyncio.create_task(_poll_and_scan(req.magnet_url, author, title, save_path))
        return {"status": "ok", "message": f"Download started → Audiobookshelf ({save_path})"}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=502, detail=f"Failed to add torrent: {e}")


async def _find_inflight_audiobook(title: str, author: str) -> dict | None:
    """Return a torrent already downloading this book, or None.

    Best-effort: if qBittorrent cannot be reached this returns None rather than
    blocking the download, matching how the Audiobookshelf check degrades.
    """
    try:
        async with httpx.AsyncClient(timeout=15.0) as client:
            login = await client.post(
                f"{QBITTORRENT_URL}/api/v2/auth/login",
                data={"username": QBITTORRENT_USER, "password": QBITTORRENT_PASS},
            )
            if login.status_code != 200:
                logger.warning("In-flight duplicate check: qBittorrent login failed")
                return None
            resp = await client.get(
                f"{QBITTORRENT_URL}/api/v2/torrents/info",
                params={"category": "audiobooks"},
            )
            resp.raise_for_status()
            return find_inflight_duplicate(title, author, resp.json())
    except Exception as e:
        logger.warning(f"In-flight duplicate check failed (proceeding anyway): {e}")
        return None


def _calibre_library_rows() -> list[tuple[str, str]]:
    """Read (title, author) for every book in the Calibre library.

    Opened read-only via a URI so a concurrent Calibre-Web write can never be
    disturbed by this check.
    """
    db = os.path.join(CWA_LIBRARY_PATH, "metadata.db")
    if not os.path.exists(db):
        return []
    conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True, timeout=5)
    try:
        return list(conn.execute(
            "SELECT b.title, ("
            "  SELECT group_concat(a.name, ' & ') FROM authors a"
            "  JOIN books_authors_link l ON l.author = a.id WHERE l.book = b.id"
            ") FROM books b"
        ))
    finally:
        conn.close()


def _calibre_formats_for(book_id: int) -> dict[str, int]:
    """Formats Calibre holds for a book, mapped to their size in bytes.

    Asked before forwarding to a Kindle so a PDF-only or too-large book can be
    left alone deliberately, rather than discovered as a failed OPDS fetch or a
    bounce off the mail relay minutes later.
    """
    db = os.path.join(CWA_LIBRARY_PATH, "metadata.db")
    if not os.path.exists(db) or book_id <= 0:
        return {}

    conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True, timeout=5)
    try:
        rows = conn.execute(
            "SELECT format, uncompressed_size FROM data WHERE book = ?", (book_id,)
        ).fetchall()
    except sqlite3.Error as e:
        logger.warning(f"Format lookup failed for book {book_id}: {e}")
        return {}
    finally:
        conn.close()
    return {r[0]: (r[1] or 0) for r in rows if r and r[0]}


def _calibre_id_for(title: str, author: str, newer_than: int | None = None) -> int | None:
    """Find a book's Calibre id by title, newest first.

    _upload_to_calibre polls OPDS for the id and gives up after ~60s, returning
    -1. A large file can still be importing at that point — a 24 MB epub did
    exactly this on 2026-08-16 — and without an id the book cannot be put on a
    shelf. The library database knows the answer as soon as Calibre commits it,
    so it is consulted directly as a second opinion.
    """
    db = os.path.join(CWA_LIBRARY_PATH, "metadata.db")
    if not os.path.exists(db):
        return None

    if not normalize_title(title):
        return None

    try:
        conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True, timeout=5)
    except sqlite3.Error as e:
        logger.warning(f"Calibre id lookup failed for {title!r}: {e}")
        return None
    try:
        rows = conn.execute(
            "SELECT b.id, b.title, ("
            "  SELECT group_concat(a.name, ' & ') FROM authors a"
            "  JOIN books_authors_link l ON l.author = a.id WHERE l.book = b.id"
            ") FROM books b ORDER BY b.timestamp DESC, b.id DESC"
        ).fetchall()
    except sqlite3.Error as e:
        logger.warning(f"Calibre id lookup failed for {title!r}: {e}")
        return None
    finally:
        conn.close()

    for book_id, book_title, book_author in rows:
        if newer_than is not None and book_id <= newer_than:
            continue
        if _same_book(book_title, book_author, title, author):
            return book_id

    return None


def _calibre_max_id() -> int | None:
    """The library's highest book id, or None when it cannot be read."""
    db = os.path.join(CWA_LIBRARY_PATH, "metadata.db")
    if not os.path.exists(db):
        return None
    try:
        conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True, timeout=5)
    except sqlite3.Error:
        return None
    try:
        return conn.execute("SELECT COALESCE(MAX(id), 0) FROM books").fetchone()[0]
    except sqlite3.Error:
        return None
    finally:
        conn.close()


def _same_book(book_title: str, book_author: str | None, title: str, author: str | None) -> bool:
    """Does a library row hold this title and author?

    The author must agree too. Titles alone let a shared surname through:
    searching for Neuromancer once matched a CISSP guide co-authored by a
    different Gibson, which then reached Anca's shelf. "Unknown Author", what a
    share with no author carries, is no author at all.
    """
    if normalize_title(book_title) != normalize_title(title):
        return False
    wanted = "" if normalize_author(author) in ("unknown author", "unknown") else author
    surname = author_surname(wanted)
    if surname and book_author and surname not in normalize_author(book_author).split():
        return False
    return True


def _calibre_book(book_id: int | None) -> tuple[str, str] | None:
    """(title, authors) of one library row, or None."""
    db = os.path.join(CWA_LIBRARY_PATH, "metadata.db")
    if not book_id or book_id <= 0 or not os.path.exists(db):
        return None
    try:
        conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True, timeout=5)
    except sqlite3.Error:
        return None
    try:
        row = conn.execute(
            "SELECT b.title, ("
            "  SELECT group_concat(a.name, ' & ') FROM authors a"
            "  JOIN books_authors_link l ON l.author = a.id WHERE l.book = b.id"
            ") FROM books b WHERE b.id = ?", (book_id,),
        ).fetchone()
    except sqlite3.Error as e:
        logger.warning(f"Calibre row lookup failed for book {book_id}: {e}")
        return None
    finally:
        conn.close()
    return (row[0] or "", row[1] or "") if row else None


async def _check_calibre_duplicate(title: str, author: str):
    """409 if the Calibre library already holds this ebook.

    The library itself was never consulted before — only the ingest folder was
    scanned by filename substring, which misses whenever the downloaded file is
    named differently from the requested title (libgen ships
    "Ray Dalio - Principles - libgen.li.mobi" for "Principles: Life and Work").
    Best-effort: an unreadable database must not block a download.
    """
    try:
        rows = await asyncio.to_thread(_calibre_library_rows)
    except Exception as e:
        logger.warning(f"Calibre duplicate check failed (proceeding anyway): {e}")
        return
    hit = find_duplicate(title, author, rows)
    if hit:
        raise HTTPException(
            status_code=409,
            detail=f"Ebook already in Calibre library: '{hit[0]}' by {hit[1]}",
        )


async def _check_cwa_duplicate(title: str, author: str):
    """Check Calibre-Web for duplicate ebooks."""
    await _check_calibre_duplicate(title, author)
    # Also catch a copy sitting in the ingest queue that Calibre has not
    # imported yet — the library check above cannot see those.
    try:
        if os.path.exists(CWA_INGEST_PATH):
            for f in os.listdir(CWA_INGEST_PATH):
                fname = f.lower()
                if title.lower().replace(" ", "") in fname.replace(" ", "").replace("-", "").replace("_", ""):
                    raise HTTPException(
                        status_code=409,
                        detail=f"Ebook already in ingest queue: {f}"
                    )
    except HTTPException:
        raise
    except Exception as e:
        logger.warning(f"CWA duplicate check failed (proceeding anyway): {e}")


async def _poll_and_scan(magnet_url: str, author: str, title: str, save_path: str = ""):
    """Poll qBittorrent until download completes, then trigger Audiobookshelf scan."""
    info_hash = None
    hash_match = _re.search(r"btih:([a-fA-F0-9]{40})", magnet_url)
    if hash_match:
        info_hash = hash_match.group(1).lower()

    poll_interval = 30
    max_polls = 120

    async with httpx.AsyncClient(timeout=15.0) as client:
        try:
            await client.post(
                f"{QBITTORRENT_URL}/api/v2/auth/login",
                data={"username": QBITTORRENT_USER, "password": QBITTORRENT_PASS},
            )
        except Exception as e:
            logger.warning(f"qBittorrent login for polling failed: {e}")
            return

        for i in range(max_polls):
            await asyncio.sleep(poll_interval)
            try:
                if info_hash:
                    resp = await client.get(
                        f"{QBITTORRENT_URL}/api/v2/torrents/info",
                        params={"hashes": info_hash},
                    )
                    torrents = resp.json()
                else:
                    resp = await client.get(
                        f"{QBITTORRENT_URL}/api/v2/torrents/info",
                        params={"category": "audiobooks"},
                    )
                    torrents = [t for t in resp.json() if t.get("save_path", "") == save_path]

                if not torrents:
                    continue

                torrent = torrents[0]
                progress = torrent.get("progress", 0)
                state = torrent.get("state", "")
                logger.info(f"[{author} - {title}] Progress: {progress:.0%}, State: {state}")

                if progress >= 1.0:
                    logger.info(f"[{author} - {title}] Download complete, triggering library scan")
                    await _trigger_audiobookshelf_scan(client)
                    return
            except Exception as e:
                logger.warning(f"Poll error: {e}")

    logger.warning(f"[{author} - {title}] Timed out waiting for download")


async def _trigger_audiobookshelf_scan(client: httpx.AsyncClient):
    if not AUDIOBOOKSHELF_TOKEN:
        return
    try:
        resp = await client.get(
            f"{AUDIOBOOKSHELF_URL}/api/libraries",
            headers={"Authorization": f"Bearer {AUDIOBOOKSHELF_TOKEN}"},
        )
        for lib in resp.json().get("libraries", []):
            lib_id = lib["id"]
            logger.info(f"Scanning library: {lib['name']} ({lib_id})")
            await client.post(
                f"{AUDIOBOOKSHELF_URL}/api/libraries/{lib_id}/scan",
                headers={"Authorization": f"Bearer {AUDIOBOOKSHELF_TOKEN}"},
            )
    except Exception as e:
        logger.warning(f"Failed to trigger Audiobookshelf scan: {e}")


